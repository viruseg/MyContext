/**
 * Сторона, которой движок делегирует всё, чего не умеет сам: показать и скрыть
 * уровни и вернуть фокус элементу, вызвавшему меню.
 *
 * @typedef {object} KeyboardHost
 * @property {() => void} closeAll закрывает всю цепочку уровней, от глубоких к
 *   корню, и возвращает фокус элементу, вызвавшему меню. Вызывается на `Tab`, на
 *   `Escape` и `ArrowLeft` корневого уровня. Активация пункта сюда не ходит: закрывает
 *   её обработчик активации, и второй вызов был бы двойным закрытием с двойным
 *   возвратом фокуса. На корневом уровне движок зовёт `focusOwner` сам сразу после
 *   `closeAll()`, и оба вызова совпадают по цели, так что второй лишний. На уходе
 *   клавишей с не-корневого уровня закрывает `closeCurrentLevel`, и возвращать фокус
 *   после него обязан вызывающий код.
 * @property {(entry: LevelEntry) => LevelEntry} openSubmenu показывает
 *   уровень-подменю и не трогает фокус: перенос на первый доступный пункт нового
 *   уровня делает сам движок сразу после вызова, и второй перенос означал бы два
 *   места показа, разошедшихся по мышиному и клавиатурному пути. Обязан быть уже
 *   заведённым: движок находит его по паре «родитель, владелец» и создавать
 *   уровни не берётся. Заводить его нужно на шаг вперёд — при активации
 *   пункта-владельца, а не в момент открытия.
 *
 *   Возвращает уровень, который показан по факту, а не переданный: показ
 *   приводит уровень к текущему составу, и состав с тех пор мог измениться —
 *   тогда ход перестраивает уровень и показывает новый. Движок обязан двигаться
 *   по возвращённому, иначе выделение встало бы на пункт уже снятого уровня.
 * @property {(entry: LevelEntry) => void} closeCurrentLevel закрывает переданный
 *   уровень вместе со всем, что открыто из него глубже, и убирает их из цепочки
 *   открытых. Вызывается на `ArrowLeft` и `Escape` не на корне, и всегда с тем
 *   уровнем, на который клавиша подействовала: движок не выводит его из
 *   `document.activeElement`, потому что при мышином показе подменю фокус остаётся
 *   в родительском уровне, и уровень, который пользователь закрывает, от фокуса не
 *   зависит.
 * @property {(item: RenderedItem, event: KeyboardEvent) => void} handOver передаёт
 *   управление пунктом наружу. Вызывается на `Enter` и `Space`, когда активен
 *   отдающий пункт: у него нет уровня, поэтому путь «показать подменю» к нему
 *   неприменим, а синтетический `click` ушёл бы мимо — отдача на клавиатуре обязана
 *   быть отдельным вызовом, а не тем же, что и у мыши. Событие едет как есть:
 *   отдающему интересно, чем пункт активирован, и координат курсора у клавиши нет.
 * @property {(entry: LevelEntry) => LevelEntry} currentLevel самый глубокий
 *   открытый уровень, не выше `entry`, — тот, на который подействуют перемещение и
 *   уход. Пока подменю не открыто, это сам `entry`. Вопрос о состоянии меню, а
 *   состояние живёт у вызывающего кода: движок о цепочке открытых уровней не знает,
 *   и отвечать за него было бы второй копией правды о том, что показано. Уровня в
 *   цепочке нет, когда он гаснет, — ответом тогда будет сам `entry`.
 * @property {() => void} focusOwner возвращает фокус элементу, вызвавшему меню.
 *   Вызывается на `Tab` и на `Escape`/`ArrowLeft` корневого уровня, то есть везде,
 *   где закрывается всё меню. Порядок обязателен: сначала `closeAll()`, потом
 *   `focusOwner()`.
 */

/**
 * @typedef {object} KeyboardController
 * @property {(event: KeyboardEvent) => void} handleKeydown разбирает клавишу по
 *   цели события, а перемещение и уход проводят по текущему уровню — см. шапку
 *   модуля. Событие вне меню и клавиша без своей ветки остаются нетронутыми.
 *   Возвращаемого значения нет и бросать нечего: у обработчика нет причины
 *   прерывать чужой обработчик.
 * @property {(entry: LevelEntry, options: RegisterLevelOptions) => void} registerLevel
 *   отдаёт уровень движку, снимает с его пунктов протухшие отметки и возвращает
 *   `activeIndex` в `-1`; при `options.focus === true` фокус встаёт на сам элемент
 *   уровня.
 *
 *   **Условие, без которого уровень мёртв для клавиатуры:** вызвать её на каждый
 *   показанный уровень. Движок узнаёт уровень не из разбора каждого нажатия, а из
 *   реестра, который наполняет только этот вызов, и на уровень вне реестра
 *   `handleKeydown` не отвечает вовсе: ни действия, ни ошибки. Открытое меню после
 *   `reset()` — тоже, пока вызывающий код не отдаст уровень заново.
 *
 *   Показ не отмечает ничего, и это не его дело: отметка появляется там, где
 *   последним дотронулись до пункта, — мышью или клавишей. Показывающий код решает
 *   только одно: переносить ли фокус. Корневой уровень его берёт на себя
 *   (`focus: true`) — иначе открытое программно меню не отвечало бы на клавиши, —
 *   а показ подменю не переносит (`focus: false`), потому что фокус остаётся в
 *   родительском уровне, а мышиный и клавиатурный пути показа обязаны вести себя
 *   одинаково.
 *
 *   На уровне без доступных пунктов заканчивается регистрацией и ничем не больше:
 *   отмечать нечего, и вызывающий код узнаёт об этом по отсутствию отметок, а не по
 *   исключению.
 * @property {(entry: LevelEntry, item: RenderedItem) => void} activateFromPointer
 *   выделяет пункт, на который встал курсор, и передаёт ему фокус. Это единственный
 *   путь выделения мышью, и потому он же причина того, что мышь перебивает
 *   клавиатуру: отметка всегда достаётся последнему, кто тронул пункт, а отдельного
 *   правила «считать стрелку от того, что под курсором» не существует и не нужно.
 *   Пункт под курсором виден по построению, поэтому долистывание списка, обязательное
 *   для клавиатурного шага, здесь не выполняется; уже отмеченный пункт атрибутов не
 *   получает заново, иначе каждое движение мыши писало бы их по кругу, — но фокус
 *   ему возвращается, если он от него ушёл: отметка снимается только внутри своего
 *   уровня, и возврат курсора к владельцу подменю иначе оставил бы подсвеченный
 *   пункт без фокуса.
 *
 *   Вызывается только для доступного пункта уровня, который движку известен: разделитель
 *   и отключённый пункт вне цикла роуминга, и выделение на них недостижимо.
 * @property {(entry: LevelEntry) => void} clearActive снимает отметки уровня,
 *   возвращает его `activeIndex` в `-1` и возвращает фокус на элемент этого же
 *   уровня, если он и был внутри. Это единственный путь сброса отметок по уходу
 *   курсора, и зовёт его вызывающий код ровно в двух случаях: курсор ушёл с дерева
 *   меню и курсор встал на зону прокрутки.
 *
 *   **Сбрасывается один уровень, а не вся цепочка.** Отметка пункта означает одно из
 *   двух: либо «курсор или клавиши выбрали этот пункт» — и тогда она остаток
 *   последнего касания, либо «подменю этого пункта открыто» — и тогда она путь
 *   раскрытия, который переживает и уход курсора, и сброс. Второе присуще уровням
 *   с открытым подменю, то есть всем, кроме последнего в цепочке, поэтому уход
 *   курсора снимает отметку последнего и оставляет отметки владельцев над ним.
 *
 *   Фокус уходит на элемент сбрасываемого уровня, а не на контейнер: меню
 *   разбирает только те клавиши, что пришли в его дерево, и после сброса первая же
 *   стрелка обязана снова прийти в меню, а не на страницу. На корень он уходит
 *   только когда сбрасывается корень, то есть когда последним в цепочке стоит он.
 *
 *   Фокус на странице не отбирается: увод курсора не отменяет того, куда фокус
 *   поставил пользователь, и на каждом движении мыши фокус выдёргивался бы у
 *   элемента формы, в котором идёт ввод.
 * @property {() => void} reset снимает отметки роуминга со всех известных
 *   уровней, возвращает их `activeIndex` в `-1` и забывает их. Фокус не забирает:
 *   куда его девать, решает вызывающий код. После вызова уровень снова нужно
 *   отдать через `registerLevel`. Повторный вызов безопасен.
 * @property {(entries: LevelEntry[]) => void} forgetLevels забывает перечисленные
 *   уровни, не трогая остальные. Отметки роуминга с них не снимаются: узлы уровня
 *   к этому моменту сняты с документа, и снимать нечего, — важно только не оставить
 *   в реестре элемент, по которому больше не придёт ни одного события. `closeAll`
 *   для этого не годится: он сносит всё меню вместе с показанными уровнями, а
 *   перестроение сносит только снесённое поддерево.
 */

/**
 * Что показывающий код сообщает движку о показанном уровне помимо самого уровня.
 *
 * @typedef {object} RegisterLevelOptions
 * @property {boolean} focus переносить ли фокус на элемент уровня. `true` — фокус
 *   встаёт на показанный уровень и держится там, пока не нажата первая клавиша
 *   навигации; `false` — фокус остаётся там, где был, то есть в родительском
 *   уровне.
 */

const MENU_SELECTOR = '.vc-menu';
const ACTIVE_ATTRIBUTE = 'data-active';
const FOCUSABLE_TAB_INDEX = 0;
const INACTIVE_TAB_INDEX = -1;
const NO_ACTIVE_ITEM = -1;

/**
 * @param {KeyboardHost} host
 * @returns {KeyboardController} движок роуминга и разбора клавиш.
 */
export function createKeyboard(host) {
  /** @type {Map<Element, LevelEntry>} уровни, которые движок знает. */
  const known = new Map();

  /**
   * Список навигации уровня: ровно те пункты, что входят в цикл. Разделитель и
   * отключённый пункт сюда не попадают — так решил рендерер, и второй фильтр
   * здесь был бы вторым мнением об одном и том же.
   *
   * @param {LevelEntry} entry
   * @returns {RenderedItem[]}
   */
  function focusableOf(entry) {
    return entry.items.filter((item) => {
      return item.focusable;
    });
  }

  /**
   * Активный пункт уровня — носитель `data-active`, а не цель события. Уровень
   * может стоять на первом пункте, пока клавиша пришла в другой: двигаться
   * надлежит от активного, иначе наведение мышью, сдвинувшее подсветку, уводило
   * бы роуминг в сторону от того, что видит пользователь.
   *
   * @param {LevelEntry} entry
   * @returns {RenderedItem | null} `null`, если активного пункта нет.
   */
  function activeItemOf(entry) {
    for (const item of entry.items) {
      if (item.element.hasAttribute(ACTIVE_ATTRIBUTE)) {
        return item;
      }
    }
    return null;
  }

  /**
   * Позиция активного пункта в списке навигации.
   *
   * @param {LevelEntry} entry
   * @returns {number} позиция или `-1`, если активного пункта нет либо он в
   *   список не входит.
   */
  function positionOf(entry) {
    const active = activeItemOf(entry);
    if (active === null) {
      return NO_ACTIVE_ITEM;
    }
    return focusableOf(entry).indexOf(active);
  }

  /**
   * Снимает отметки роуминга со всех пунктов уровня и возвращает `activeIndex`
   * в `-1`. Разделитель отметок не имеет и не получает: у него нет `tabindex`
   * вовсе, и число в никуда было бы его единственным отличием от пункта.
   *
   * Отметка снимается и с пункта, который из кольца выпал: `isEnabledAction`
   * перечитывается при показе, и пункт, активный в прошлом показе, мог стать
   * отключённым к следующему. Оставить на нём `tabindex="0"` — значит оставить
   * `Tab` на элементе, который нельзя выбрать, а приглушение отключённой строки
   * наложилось бы на подсветку выбранной. Такого сочетания быть не должно вовсе,
   * и на него рассчитывает приглушение в CSS.
   *
   * Отсеиваются разделители, а не отключённые: признак «это не пункт» один, и он
   * же — `key`, — а `tabindex` у разделителя не бывает вовсе, и присваивание
   * создало бы у него атрибут, которого там не было никогда.
   *
    * Перебор идёт по `entry.items`, а не по `focusableOf`: список навигации
    * аллоцируется на каждый вызов, а вызывающий код не заинтересован в том, какие
    * пункты попадут в сброс, — его интересует только чтобы на уровне не осталось
    * отметок вовсе.
    *
    * @param {LevelEntry} entry
    * @returns {void}
    */
  function clearMarksOf(entry) {
    for (const item of entry.items) {
      if (item.key === null) {
        continue;
      }
      item.element.removeAttribute(ACTIVE_ATTRIBUTE);
      item.element.tabIndex = INACTIVE_TAB_INDEX;
    }
    entry.activeIndex = NO_ACTIVE_ITEM;
  }

  /**
   * Единственный писатель отметки роуминга: переводит пункт в активное состояние
   * и запоминает его индексом уровня. Отметка с предыдущего активного снимается
   * здесь же, иначе на уровне осталось бы два `tabindex="0"` и два `data-active`
   * сразу, а `Tab` зациклил бы меню на месте. Фокус сюда не входит: оба вызова
   * передают его одинаково, различаются они только долистыванием.
   *
   * @param {LevelEntry} entry
   * @param {RenderedItem} item
   * @returns {void}
   */
  function markActive(entry, item) {
    const previous = activeItemOf(entry);
    if (previous !== null && previous !== item) {
      previous.element.tabIndex = INACTIVE_TAB_INDEX;
      previous.element.removeAttribute(ACTIVE_ATTRIBUTE);
    }
    item.element.tabIndex = FOCUSABLE_TAB_INDEX;
    item.element.setAttribute(ACTIVE_ATTRIBUTE, '');
    // Индекс в `entry.items`, а не в списке навигации: между доступными пунктами
    // стоят отключённые и разделители, и индексы в разных списках не совпадают.
    entry.activeIndex = entry.items.indexOf(item);
    known.set(entry.element, entry);
  }

  /**
   * Передаёт активность пункту уровня и фокус ему же, затем долистывает список.
   *
   * @param {LevelEntry} entry
   * @param {RenderedItem} item
   * @returns {void}
   */
  function activate(entry, item) {
    markActive(entry, item);
    // Передача фокуса и долистывание списка — две разные вещи, и `preventScroll`
    // гасит обе: он запрещает прокрутку, которую браузер сделал бы сам, а не ту,
    // которую просят. Список прокручиваемый, и без второй строки активный пункт
    // ушёл бы за его край вместе с фокусом.
    item.element.focus({ preventScroll: true });
    item.element.scrollIntoView({ block: 'nearest' });
  }

  /**
   * Выделение мышью: ровно тот же `activate`, что зовёт клавиатурный `moveTo`, но
   * без долистывания — пункт под курсором и так виден, а `scrollIntoView` дёргал бы
   * список на каждом движении. Уже отмеченный пункт атрибутов не получает заново.
   *
   * @param {LevelEntry} entry
   * @param {RenderedItem} item доступный пункт этого уровня.
   * @returns {void}
   */
  function activateFromPointer(entry, item) {
    if (item.element.hasAttribute(ACTIVE_ATTRIBUTE)) {
      // Атрибутов пункт не получает заново, а вот фокус возвращается: отметка
      // снимается только внутри своего уровня, поэтому при уходе курсора в подменю
      // отметка владельца там и остаётся. Возврат курсора к владельцу без фокуса
      // оставил бы подсвеченный пункт без него, и клавиши поехали бы по подменю,
      // которое пользователь покинул.
      if (document.activeElement !== item.element) {
        item.element.focus({ preventScroll: true });
      }
      return;
    }
    markActive(entry, item);
    item.element.focus({ preventScroll: true });
  }

  /**
   * Сброс отметок уровня: снимаются отметки и `activeIndex` возвращается в `-1`,
   * а фокус, если он был внутри уровня, встаёт на сам элемент уровня.
   *
   * Фокус переносится только когда он стоял внутри сбрасываемого уровня. Фокус
   * соседнего уровня не трогается: отметки соседа под сброс не попадают, и
   * переносить фокус туда было бы перемещением без причины.
   *
   * @param {LevelEntry} entry уровень, с которого снимаются отметки.
   * @returns {void}
   */
  function clearActive(entry) {
    clearMarksOf(entry);
    const active = document.activeElement;
    if (active !== null && entry.element.contains(active)) {
      entry.element.focus({ preventScroll: true });
    }
  }

  /**
   * Переход по кругу: позиция берётся по модулю длины списка, поэтому и
   * `End` с длиной минус один, и шаг с первого на последний, и обратный шаг с
   * нулевого работают одним правилом.
   *
   * @param {LevelEntry} entry
   * @param {number} position позиция в списке навигации, любая целая.
   * @returns {void}
   */
  function moveTo(entry, position) {
    const focusable = focusableOf(entry);
    if (focusable.length === 0) {
      return;
    }
    const length = focusable.length;
    activate(entry, focusable[((position % length) + length) % length]);
  }

  /**
   * Подменю пункта — по паре «родитель, владелец», тем же поиском, каким слой
   * находит уже заведённый уровень.
   *
   * @param {LevelEntry} entry
   * @param {RenderedItem} item
   * @returns {LevelEntry | null} `null`, если подменю не заведено.
   */
  function submenuOf(entry, item) {
    for (const child of entry.children) {
      if (child.ownerItem === item) {
        return child;
      }
    }
    return null;
  }

  /**
   * Уход с текущего уровня: закрыть его и вернуть фокус туда, откуда пришли.
   * На не-корневом уровне это пункт-владелец, на корневом — элемент, вызвавший
   * меню: оставить фокус в закрывающем уровне нельзя, закрытие отложено и фокус
   * упал бы на `<body>`.
   *
   * Закрывается именно `entry`, а не уровень, где стоит фокус: при мышином показе
   * подменю фокус остался в родителе, и выведенный из `document` уровень оказался бы
   * не тем, который пользователь закрывает.
   *
   * @param {LevelEntry} entry покидаемый уровень.
   * @returns {void}
   */
  function leaveLevel(entry) {
    const parent = entry.parent;
    if (parent === null) {
      host.closeAll();
      host.focusOwner();
      return;
    }
    host.closeCurrentLevel(entry);
    const owner = entry.ownerItem;
    // Владелец у подменю есть по построению слоя, и `focusable` у него по решению
    // рендерера тоже: владельцем становится только доступный пункт, а уровень
    // заводится лишь владельцу. То есть вторая проверка сегодня недостижима и
    // оставлена защитой от будущего рендерера: отметка роуминга неактивному пункту
    // не полагается, иначе `Tab` зациклил бы меню на неактивном элементе. Своим
    // кейсом она не закрыта — состояние «открытое подменю при неактивном владельце»
    // нельзя построить даже вручную, `createLayer` на нём бросает; кейс этой
    // недостижимости лежит в `tests/e2e/keyboard.spec.js`.
    if (owner !== null && owner.focusable) {
      activate(parent, owner);
    }
  }

  /**
   * Отдаёт уровень движку и приводит его к состоянию «выделения нет»: отметки
   * снимаются со всех пунктов навигации, `activeIndex` возвращается в `-1`.
   * Протухшая отметка опасна тем, что пережила бы перестроение уровня и висела бы
   * на пункте, которого движок больше не знает, — а `Tab` зациклил бы меню на нём.
   *
   * @param {LevelEntry} entry
   * @param {RegisterLevelOptions} options
   * @returns {void}
   */
  function registerLevel(entry, options) {
    clearMarksOf(entry);
    known.set(entry.element, entry);
    // Фокус с `preventScroll: true` — по той же причине, что и в `activate`: меню
    // `position: fixed`, и без флага браузер сдвинул бы страницу в тот самый момент,
    // когда меню только что появилось.
    if (options.focus) {
      entry.element.focus({ preventScroll: true });
    }
  }

  /**
   * @param {KeyboardEvent} event
   * @returns {void}
   */
  function handleKeydown(event) {
    const target = event.target;
    if (!(target instanceof Element)) {
      return;
    }
    // Клавиша вне меню не должна съедаться никогда, иначе меню, закрытое вкладкой,
    // сломало бы навигацию по странице. Внутри меню целью может оказаться и сам
    // элемент уровня: пока активного пункта нет, фокус стоит на нём, и его клавиши
    // обязаны разбираться так же, как клавиши на пункте.
    const level = target.closest(MENU_SELECTOR);
    if (level === null) {
      return;
    }
    const entry = known.get(level);
    if (entry === undefined) {
      return;
    }
    const active = activeItemOf(entry);
    // Уровень, на который подействует перемещение и уход. Ответ берётся у хоста по
    // цепочке открытых уровней и совпадает с `entry`, пока подменю не открыто, —
    // то есть на каждой клавише обычного меню это один и тот же уровень.
    const current = host.currentLevel(entry);
    switch (event.key) {
      case 'ArrowDown': {
        // Случай «активного пункта нет» разбирать не нужно: у такого уровня
        // позиция равна `-1`, и `-1 + 1` — это ноль, то есть первый доступный
        // пункт. Отдельная ветка здесь была бы вторым ответом на один вопрос.
        moveTo(current, positionOf(current) + 1);
        break;
      }
      case 'ArrowUp': {
        const position = positionOf(current);
        // А вот здесь отдельная ветка нужна: `-1 - 1` — это минус два элемента
        // списка, то есть предпоследний вместо последнего.
        moveTo(current, position < 0 ? -1 : position - 1);
        break;
      }
      case 'Home': {
        moveTo(current, 0);
        break;
      }
      case 'End': {
        moveTo(current, focusableOf(current).length - 1);
        break;
      }
      case 'ArrowRight': {
        // Раскрытие смотрит на активный пункт того уровня, откуда пришла клавиша:
        // выделение стоит на владельце в родительском уровне, и `ArrowRight` на
        // нём — вход в его подменю, открытое мышью или нет.
        if (active === null || !active.hasSubmenu) {
          break;
        }
        const submenu = submenuOf(entry, active);
        if (submenu === null) {
          break;
        }
        moveTo(host.openSubmenu(submenu), 0);
        break;
      }
      case 'ArrowLeft': {
        leaveLevel(current);
        break;
      }
      case 'Enter':
      case ' ': {
        // Активация смотрит на активный пункт уровня, из которого пришла клавиша, —
        // как и `ArrowRight`: текущий уровень при открытом подменю отвечает на
        // вопрос «что видно», а этот — на вопрос «что выбрано».
        if (active === null) {
          break;
        }
        // Владелец подменю активируется открытием: пустое подменю открывать не
        // чего, а непустое открывается целиком.
        if (active.hasSubmenu) {
          const submenu = submenuOf(entry, active);
          if (submenu !== null) {
            moveTo(host.openSubmenu(submenu), 0);
          }
          break;
        }
        // Отдающий управление активируется так же, как владелец подменю, — но идти
        // ему некуда: уровня у него нет, и открывать нечего. Проверка идёт до клика
        // ниже, иначе отдающий получил бы синтетический `click`, а это был бы путь
        // активации, на котором у него нет ни подменю, ни смысла.
        if (active.handsOff) {
          host.handOver(active, event);
          break;
        }
        // Клик, а не прямой вызов коллбэка: карты активов у движка нет, а путь
        // активации должен быть один и тот же для мыши и для клавиатуры.
        //
        // Закрытия здесь нет, и это не потеря: единственный обработчик активации
        // закрывает меню сам, в своём `finally`, — и закрывает по любому поводу, в
        // том числе когда действие пункта открыло меню заново. Второй вызов
        // `closeAll()` был бы двойным закрытием с двойным возвратом фокуса, причём
        // на уже закрытом меню.
        active.element.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true }));
        break;
      }
      case 'Escape': {
        leaveLevel(current);
        break;
      }
      case 'Tab': {
        host.closeAll();
        host.focusOwner();
        break;
      }
      default:
        // Ветки нет — событие не наше: `preventDefault` ниже до него не доходит.
        return;
    }
    event.preventDefault();
  }

  /**
   * @returns {void}
   */
  function reset() {
    for (const entry of known.values()) {
      clearMarksOf(entry);
    }
    known.clear();
  }

  /**
   * @param {LevelEntry[]} entries уровни, снятые с документа слоем.
   * @returns {void}
   */
  function forgetLevels(entries) {
    for (const entry of entries) {
      known.delete(entry.element);
    }
  }

  return {
    handleKeydown,
    registerLevel,
    activateFromPointer,
    clearActive,
    reset,
    forgetLevels,
  };
}
