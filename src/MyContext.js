/**
 * @typedef {object} MyContextOptions
 * @property {'auto' | 'light' | 'dark'} [theme] тема оформления всех уровней,
 *   `'auto'` по умолчанию. Иное значение отклоняется, а не проходит в разметку.
 * @property {number} [animationDuration] длительность входа, выхода и отложенного
 *   закрытия, мс, `DEFAULT_ANIMATION_DURATION` по умолчанию. Величина одна и та же
 *   у всех трёх, иначе выход не совпадёт с задержкой снятия. Требуется конечное
 *   неотрицательное число: `NaN` дал бы недействительный токен `NaNms`, и переход
 *   схлопнулся бы в ноль молча.
 * @property {string} [label] доступное имя меню, `DEFAULT_MENU_LABEL` по умолчанию:
 *   имя у уровня обязательно (`createLayer` требует строку), а пустое имя не читается
 *   и не проходит аудит — потому и проверяется, а не подставляется по умолчанию.
 * @property {number} [autoHideDistance] расстояние от показанных уровней до курсора,
 *   px, после которого меню скрывает себя само, `DEFAULT_AUTO_HIDE_DISTANCE` по
 *   умолчанию. `0` — правило выключено. Меряется до ближайшего уровня открытой
 *   цепочки, то есть уход в сторону закрывает меню, а уход в сторону открытого
 *   подменю — нет. Требуется конечное неотрицательное число: `NaN` в сравнении
 *   ложен всегда, и правило молча превратилось бы в «не скрываться никогда».
 * @property {number} [scale] множитель размеров меню, `DEFAULT_SCALE` по умолчанию.
 *   Увеличивает или уменьшает целиком: высоту пункта, кегль, иконки, шевроны,
 *   отступы, скругления, рамку, разделители и зоны прокрутки, — и делает это на
 *   каждом уровне, включая подменю. Требуется конечное число больше нуля: ноль
 *   схлопнул бы меню до негодных габаритов, а `NaN` дал бы в `calc()` раскладку,
 *   которой нет, и обе поломки не обратимы без единой ошибки. Верхней границы
 *   нет: предельные `max-width` и `max-height` не дают меню выйти за вьюпорт, так
 *   что большое значение означает длинный список, а не поломку. Значения меньше
 *   единицы уменьшают меню — см. [`scale`](README.md#scale).
 * @property {PressAndHoldMode} [pressAndHold] чем меню открывается и когда
 *   закрывается, `DEFAULT_PRESS_AND_HOLD` по умолчанию. `'none'` — прежнее
 *   поведение: показ по правому клику, закрытие как угодно. Любое другое значение
 *   переводит меню на жизненный цикл удержания: нажатие показывает его в точке
 *   нажатия, отпускание закрывает, и отпускание над доступным пунктом исполняет его
 *   действие. Значение называет кнопку, а не включает жест, — см.
 *   [`pressAndHold`](README.md#pressandhold). Действует всё время жизни меню, и
 *   программный `open()` под ним не меняется.
 * @property {(event: PointerEvent) => boolean | Promise<boolean>} [isArmableAction]
 *   предикат, решающий, вооружать ли нажатие жест удержания. Зовется на каждом
 *   нажатии подходящей кнопки до показа меню и получает живой `PointerEvent`
 *   нажатия, а ответ не из `true` оставляет меню закрытым. Ответом может быть
 *   промис: меню показывается, когда предикат ответит. Смысл в том, что автор
 *   узнаёт цель нажатия раньше показа: подписи и доступность пунктов читаются при
 *   показе, и без предиката они отвечали бы на предыдущий показ. Осмысленна только
 *   при `pressAndHold`, отличном от `'none'`: при `'none'` жеста нажатия нет, и опция
 *   молчала бы. Отказ предиката не открывает меню, снимает вооружение и приходит
 *   событием `error` с `source` `'isArmableAction'`; неотменённый подписчиком уходит
 *   на страницу как непойманная ошибка. См.
 *   [`isArmableAction`](README.md#isarmableaction).
 *
 *   **Асинхронный предикат гасит выделение текста на каждом нажатии.** Решение о
 *   `pressAndHold: 'left'` принимается синхронно, до ответа предиката: иначе
 *   протяжка курсора к пункту начала бы выделять текст под меню. Плата за это —
 *   при `pressAndHold: 'left'` с асинхронным предикатом выделение подавляется
 *   вообще на каждом нажатии в контейнере, включая те, где предикат ответит
 *   `false`.
 * @property {boolean} [destroyOnClose] разбирать ли экземпляр при закрытии,
 *   `false` по умолчанию. Нужен меню, которое автор заводит на один показ: ссылки
 *   на такой экземпляр ни у кого нет, а `destroy()` звать некому, и без опции он
 *   переживает закрытие вместе со слушателем `contextmenu` на своём контейнере,
 *   глобальными правилами закрытия, уровнями в DOM и записью в реестре живых. С
 *   закрытием разбирается всё это разом, и следующий показ требует нового
 *   экземпляра.
 *
 *   Разбор наступает на любом закрытии — закрытие у экземпляра одно, — и
 *   объявляет экземпляр уничтоженным сразу: `open`, `attach`, `detach` и `close`
 *   бросают `Error` ровно как после `destroy()`, а контейнер перестаёт открывать
 *   меню. Уровни при этом снимаются не сразу: разбор отложен до конца выхода, иначе
 *   меню, рассчитанное на один показ, пропадало бы ещё и без анимации. Под
 *   `prefers-reduced-motion: reduce` выхода нет, и разбор мгновенен.
 *
 *   Переоткрытие на месте — повторный `open()` по уже открытому меню — закрытием
 *   не считается: это тот же показ, и погасшие уровни доводятся новым.
 *
 *   См. [`destroyOnClose`](README.md#destroyonclose).
 */

