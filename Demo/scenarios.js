/**
 * Сценарий демонстрационной страницы.
 *
 * @typedef {object} Scenario
 * @property {string} id значение атрибута `data-scenario` у блока сценария.
 *   Один и тот же ключ стоит в `index.html` и здесь, и `Demo/demo.js` отказывается
 *   строить страницу при расхождении.
 * @property {string} title подпись блока и доступное имя меню сценария.
 * @property {string} [hint] подсказка блока вместо общей. Своя подсказка нужна
 *   блоку, который делает не то же, что остальные, — иначе читатель демо
 *   увидел бы отличие только по факту, а не по подписи под ним.
 * @property {number} [autoHideDistance] порог автоскрытия для меню сценария, px.
 *   `undefined` — обычное поведение, то есть меню держится, пока его не закрыли
 *   явно.
 * @property {import('../src/constants.js').PressAndHoldMode} [pressAndHold] режим
 *   удержания для меню сценария. `undefined` — прежнее поведение, то есть показ по
 *   правому клику.
 * @property {boolean} [openWithArmed] показывать ли меню сценария вызывающим кодом
 *   с `armed`, а не привязкой блока. Сценарию нужен собственный показ, чтобы
 *   отличаться от обычного удержания: вооружает жест тот, кто держит кнопку, и в
 *   демо этим «кем» может быть только страница.
 * @property {boolean} [openFromButton] показывать ли меню сценария кнопкой в блоке
 *   и оставлять ли экземпляр непривязанным. Сценарий показывает показ из чужого
 *   кода, а он виден только у непривязанного экземпляра: у привязанного правила
 *   закрытия и так подняты, и `dismissible` ничего бы не менял.
 * @property {Array<MenuItem | SeparatorItem>} items пункты корневого уровня.
 */

/**
 * Разделитель уровня. Функция, а не объявленная константа: разделить два
 * сценария нечем, а переиспользовать один узел между уровнями нельзя, потому что
 * уровни строятся отдельно и каждый получает собственную копию.
 *
 * @returns {SeparatorItem}
 */
function separator() {
  return { type: 'separator' };
}

/**
 * Идентификатор блока, чей журнал пишет отдача управления.
 *
 * Отдельная константа, потому что обработчики `handoffAction` задаются в описании
 * сценария, а не в функции, которой передаётся блок: идентификатор пришлось бы
 * либо захватить извне, либо передавать через само описание — и оба пути тащили бы
 * в сценарий то, что принадлежит странице.
 */
const HANDOFF_ID = 'handoff';

/**
 * Запись в журнал сценария по событию активации.
 *
 * Отдача управления приходит событием, и журналу полезно знать, чем именно: по
 * наведению, по нажатию или с клавиатуры — три разных обстоятельства одного и того
 * же вызова. Само событие в журнал не пишется: оно живёт одну секунду и читателю
 * демо ничего не скажет, а координаты его привяжут запись к конкретному запуску.
 *
 * @param {string} scenarioId значение `data-scenario` у блока.
 * @param {string} what что именно произошло.
 * @param {Event} event событие активации.
 * @returns {void}
 */
function log(scenarioId, what, event) {
  const block = document.querySelector(`[data-scenario="${scenarioId}"]`);
  const journal = block === null ? null : block.querySelector('.demo-log');
  if (journal === null) {
    return;
  }
  const row = document.createElement('li');
  row.textContent = `${what} (${event.type})`;
  journal.appendChild(row);
}

