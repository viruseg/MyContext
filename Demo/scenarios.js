/**
 * Наборы меню демонстрационной страницы: по одному на каждый проверяемый случай
 * библиотеки.
 *
 * Данные, а не разметка: пункты не строятся заранее, дерево каждого уровня
 * рендерится лениво при первом показе, поэтому страница держит только описания.
 * Из этого следует и то, что страница не может стать источником тихих поломок
 * отрисовки: единственное, что здесь можно испортить, — сами описания, и их
 * проверяет `tests/e2e/demo.spec.js`.
 *
 * **Действия вешает страница, а не данные.** `Demo/demo.js` обходит дерево
 * (`withItemActions`) и навешивает действие каждому пункту всех уровней, а
 * описания здесь остаются чистыми: новый пункт в описании сразу получает
 * рабочий клик, и журналу кликов не нужно знать, какие пункты есть. Одно
 * исключение — пункт-владелец: журнал навешивается на него только при
 * `ownAction`, потому что клик по владельцу без своего действия раскрывает
 * подменю и журнала не касается. Пометку ставят оба вида владельцев в каждом
 * блоке, иначе различать их было бы нечем.
 *
 * **Подменю не содержат разделителей.** Хотя контракт их и допускает, разделитель
 * внутри подменю потребовал бы либо приведения типов, либо расширения типа в
 * `src/`, а `src/` — это библиотека и за пределами демо. Разделители стоят в
 * корневых уровнях, где тип списка позволяет их.
 */

/**
 * @typedef {import('../src/renderer.js').MenuItem} MenuItem
 * @typedef {import('../src/renderer.js').SeparatorItem} SeparatorItem
 */

/**
 * Пункт описания сценария: обычный `MenuItem` и демо-пометка `ownAction`.
 *
 * `ownAction` отвечает на вопрос, которого нет у библиотеки: **навешивать ли на
 * пункт-владелец журнал кликов.** Действия вешает страница (`Demo/demo.js`), и без
 * пометки владелец получил бы `action` вместе со всеми остальными — то есть стал бы
 * кликабельным, а клик по нему перестал бы раскрывать подменю. Каждый блок демо
 * показывает оба вида владельца рядом, и без пометки второй из них нечем было бы
 * отличить от первого.
 *
 * @typedef {MenuItem & { ownAction?: boolean }} DemoItem
 */

/**
 * Сценарий демонстрационной страницы.
 *
 * @typedef {object} Scenario
 * @property {string} id значение атрибута `data-scenario` у блока сценария.
 *   Один и тот же ключ стоит в `index.html` и здесь, и `Demo/demo.js` отказывается
 *   строить страницу при расхождении.
 * @property {string} title подпись блока и доступное имя меню сценария.
 * @property {string} [hint] подсказка блока вместо общей. Своя подсказка нужна
 *   блоку, который делает не то же, что остальные, — иначе читатель демо
 *   увидел бы отличие только по факту, а не по подписи под ним.
 * @property {number} [autoHideDistance] порог автоскрытия для меню сценария, px.
 *   `undefined` — обычное поведение, то есть меню держится, пока его не закрыли
 *   явно.
 * @property {import('../src/constants.js').PressAndHoldMode} [pressAndHold] режим
 *   удержания для меню сценария. `undefined` — прежнее поведение, то есть показ по
 *   правому клику.
 * @property {boolean} [openFromButton] показывать ли меню сценария кнопкой в блоке
 *   и оставлять ли экземпляр непривязанным. Сценарий показывает показ из чужого
 *   кода, а он виден только у непривязанного экземпляра: у привязанного правила
 *   закрытия и так подняты, и `dismissible` ничего бы не менял.
 * @property {boolean} [scaleControl] строить ли в блоке ползунок множителя
 *   размеров. `undefined` — у блока нет управления, и его меню живёт в базовом
 *   размере. Начальное положение ползунка — `DEFAULT_SCALE`, а сам диапазон
 *   объявлен в `Demo/demo.js`: он относится к элементу управления, а не к данным
 *   меню, и держать его в описании сценария было бы вторым местом, где живёт
 *   одно и то же число.
 * @property {boolean} [focusJournal] навесить ли на пункты блока события фокуса и
 *   завести второй журнал. `undefined` — у блока один журнал, кликов, и события
 *   фокуса в него не пишутся: журнал кликов читают кейсы `tests/e2e/demo.spec.js`,
 *   и запись о наведении смешала бы два разных события в одном списке.
 * @property {Array<DemoItem | SeparatorItem>} items пункты корневого уровня.
 */

/**
 * Разделитель уровня. Функция, а не объявленная константа: разделить два
 * сценария нечем, а переиспользовать один узел между уровнями нельзя, потому что
 * уровни строятся отдельно и каждый получает собственную копию.
 *
 * @returns {SeparatorItem}
 */
function separator() {
  return { type: 'separator' };
}

