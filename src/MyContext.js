/**
 * Название режима удержания.
 *
 * @param {unknown} value
 * @returns {value is PressAndHoldMode}
 */
function isPressAndHoldMode(value) {
  // `some` со сравнением, а не `includes`: проверяется значение, пришедшее от
  // автора и типизированное как `unknown`, а `includes` требует уже готового
  // элемента списка и такой аргумент отверг бы на уровне типов.
  return PRESS_AND_HOLD_MODES.some((mode) => mode === value);
}

/**
 * Имя кнопки контракта → числовой код `PointerEvent.button`.
 *
 * Живёт отдельно от `PRESS_AND_HOLD_MODES`: пресет `pressAndHold` называет кнопку
 * и может её не называть вовсе (`'any'`), а контракт `openSubmenu(x, y, handoff)`
 * приносит имя извне и отвечает кодом напрямую. Таблица нужна обоим, а разные
 * словари означали бы, что рано или поздно один из них разойдётся с остальными.
 *
 * @type {Readonly<Record<'left' | 'middle' | 'right' | 'back' | 'forward', number>>}
 */
const HOLD_BUTTON_CODES = Object.freeze({
  left: PRIMARY_MOUSE_BUTTON,
  middle: MIDDLE_MOUSE_BUTTON,
  right: RIGHT_MOUSE_BUTTON,
  back: 3,
  forward: 4,
});

/**
 * Числовой код `PointerEvent.button` → имя кнопки контракта.
 *
 * Обратный проход по той же таблице, а не вторая: две таблицы разошлись бы при
 * первом же добавлении кнопки, и `handoff` стал бы называть не ту.
 *
 * @param {number | null} code код кнопки либо `null`, если кнопка не названа.
 * @returns {'left' | 'middle' | 'right' | 'back' | 'forward' | null} имя кнопки,
 *   либо `null` для не названной и для кода, которого контракт не знает.
 */
function buttonNameOf(code) {
  if (code === null) {
    return null;
  }
  for (const [name, value] of Object.entries(HOLD_BUTTON_CODES)) {
    if (value === code) {
      return /** @type {'left' | 'middle' | 'right' | 'back' | 'forward'} */ (name);
    }
  }
  return null;
}

/**
 * Описание живого жеста, передаваемое меню как сабменю чужого меню.
 *
 * `held` отвечает на вопрос «кнопка сейчас зажата», а `button` — «чьё отпускание
 * закончит жест». Это две разные вещи, и путать их нельзя: handoff передаёт жест,
 * а не политику показа, поэтому `pressAndHold` ребёнка от него не меняется.
 * Меню, у которого `pressAndHold` настроен на другую кнопку, всё равно принимает
 * ту, которой его открыли.
 *
 * `button: null` при `held: true` значит «кнопка зажата, но какая — неизвестно»:
 * так шлёт меню с `pressAndHold: 'any'`, и ребёнок обязан принять отпускание любой
 * кнопки. При `held: false` поле справочное: жеста нет, и на показ оно не влияет.
 *
 * @typedef {object} SubmenuHandoff
 * @property {'left' | 'middle' | 'right' | 'back' | 'forward' | null} button кнопка,
 *   которой держится жест; `null` — любая кнопка.
 * @property {boolean} held жив ли жест прямо сейчас.
 */

/**
 * Разбор описания жеста на входе показа как сабменю.
 *
 * Проверяется по форме, а не по смыслу: негодное значение молча превратилось бы в
 * показ без жеста, и меню открылось бы, но его отпускание закрывать ничего не стало
 * бы — то есть автор передал handoff, а меню повело себя как при его отсутствии.
 *
 * `undefined` — законное «не задан», и оно же означает показ без жеста. `null`
 * таковым не является: это «не объект», и ошибка обязана быть громкой.
 *
 * @param {unknown} handoff третий аргумент `openSubmenu`, как его передал вызывающий.
 * @param {string} source имя вызывающего для сообщения об ошибке.
 * @returns {{ armed: boolean, button: number | null }} вооружать ли жест и на какой
 *   кнопке; `button: null` означает любую кнопку.
 * @throws {TypeError} на негодном значении.
 */
function readHandoff(handoff, source) {
  if (handoff === undefined) {
    return { armed: false, button: null };
  }
  if (!isRecord(handoff)) {
    throw new TypeError(`${source}: handoff должен быть объектом`);
  }
  if (typeof handoff.held !== 'boolean') {
    throw new TypeError(`${source}: handoff.held должен быть истиной или ложью`);
  }
  if (handoff.held === false) {
    return { armed: false, button: null };
  }
  if (handoff.button === null) {
    return { armed: true, button: null };
  }
  const name = /** @type {string} */ (handoff.button);
  // Имя ищется **своим** свойством, а не простым обращением к таблице: таблица
  // кодов — обычный объект и наследует `constructor`, `toString`, `__proto__`.
  // Такое имя прошло бы проверку «в таблице есть такая строка» (там лежит не
  // `undefined`), вооружило бы жест числом, которого не бывает, и отпускание,
  // обязаное закрыть меню, не закрыло бы его никогда. Отвергать такое имя должен
  // и соседний пакет, принимающий тот же контракт: разойтись здесь нельзя, потому
  // что контракт один на оба.
  if (typeof name !== 'string' || !Object.hasOwn(HOLD_BUTTON_CODES, name)) {
    throw new TypeError(`${source}: handoff.button — неизвестная кнопка «${String(handoff.button)}»`);
  }
  return { armed: true, button: HOLD_BUTTON_CODES[/** @type {'left' | 'middle' | 'right' | 'back' | 'forward'} */ (name)] };
}

/**
 * Номер кнопки, которую называет режим `pressAndHold`, либо `null`, если он
 * кнопку не называет.
 *
 * `'none'` — не удержание вовсе, `'any'` — любая кнопка, и оба отвечают `null`:
 * решение о том, вооружать ли жест, принимает вызывающий, а эта функция. Смешивать
 * два ответа в один тип значило бы вязать проверку `=== PRIMARY_MOUSE_BUTTON` с
 * вопросом «выключено ли», и каждый второй вызов получал бы проверку на два
 * значения.
 *
 * @param {PressAndHoldMode} mode
 * @returns {number | null}
 */
function pressButtonOf(mode) {
  const code = HOLD_BUTTON_CODES[/** @type {keyof typeof HOLD_BUTTON_CODES} */ (mode)];
  return code === undefined ? null : code;
}

