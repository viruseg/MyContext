/**
 * Тема оформления и прочие величины, которые меню отдаёт CSS.
 *
 * Значение `data-vc-theme` читает `styles/mycontext.css`:
 * `auto` остаётся связанным с системной схемой, `light` и `dark` задают тему
 * принудительно. Модуль ничего не знает про медиазапросы и про каскад — он
 * только ставит атрибут, и вся логика выбора палитры остаётся в CSS.
 *
 * Имя модуля осталось за темой, что была в нём первой, хотя dwells в нём уже три
 * величины: тема, длительность анимаций и множитель масштаба. Все три — свойства
 * одного уровня, выраженные в CSS, и все три пишутся одинаково: инлайном на узел,
 * в обход авторской таблицы стилей.
 */

/**
 * Прописывает тему оформления элементу меню.
 *
 * @param {HTMLElement} element корневой элемент уровня меню.
 * @param {'auto'|'light'|'dark'} theme тема оформления. `auto` оставляет выбор за
 *   системной схемой, `light` и `dark` переопределяют её.
 * @returns {void}
 */
export function applyTheme(element, theme) {
  element.dataset.vcTheme = theme;
}

/**
 * Прописывает длительность анимаций элементу меню.
 *
 * Значение уходит в `--vc-animation-duration`, откуда его берут переходы меню,
 * пункта и шеврона, поэтому вызывающий код управляет всей анимацией одним
 * значением, а не обходом правил.
 *
 * @param {HTMLElement} element корневой элемент уровня меню.
 * @param {number} durationMs длительность, мс. Отрицательное значение браузер
 *   трактует как ноль.
 * @returns {void}
 */
export function applyAnimationDuration(element, durationMs) {
  element.style.setProperty('--vc-animation-duration', `${durationMs}ms`);
}

/**
 * Прописывает множитель масштаба элементу меню.
 *
 * Значение уходит в `--vc-scale`, откуда его берёт каждая длина внутри меню —
 * от высоты пункта до толщины рамки, — поэтому один множитель меняет размер
 * целиком, а не по одному правилу за раз. Меню при этом остаётся в гарантированных
 * границах вьюпорта: предельные `max-width` и `max-height` выведены из
 * `--vc-padding`, который множителем не тронут, и длинный список уходит в
 * прокрутку, а не за край.
 *
 * Множитель, а не `transform: scale()`: преобразование не меняет раскладку, и
 * движок позиционирования, который меряет уровень по вычисленным `width` и
 * `height`, увидел бы доtransformную величину и положил бы меню не туда.
 * Множитель меняет раскладку, поэтому замер возвращает уже увеличенный размер.
 *
 * @param {HTMLElement} element корневой элемент уровня меню.
 * @param {number} scale множитель размеров. Требуется конечное число больше нуля;
 *   проверяет конструктор `MyContext`, здесь значение приходит уже годным.
 * @returns {void}
 */
export function applyScale(element, scale) {
  element.style.setProperty('--vc-scale', String(scale));
}
