/**
 * @typedef {object} OpenOptions
 * @property {boolean} [armed] показать меню внутри уже начатого жеста удержания.
 *   Кнопка, названная `options.pressAndHold`, считается уже зажатой: меню закроется на
 *   её отпускании, а под курсором в этот момент окажется доступный пункт — его
 *   действие исполнится. Нужен вызывающему коду, который держит кнопку сам и открывает
 *   меню уже после нажатия: вооружения от нажатия по контейнеру не было, а закрыть
 *   меню должен тот же жест. По умолчанию `false`, и без опции поведение прежнее.
 *   Требует `options.pressAndHold`, отличного от `'none'`: при `'none'` кнопки нет, и
 *   закрывать меню будет нечем.
 * @property {boolean} [dismissible] показать меню, готовое к тому, чтобы его убрали
 *   обычными правилами: клик вне меню, правый клик вне меню, прокрутка, `resize`,
 *   уход вкладки в фон, потеря фокуса окна и — если он задан — `autoHideDistance`.
 *   Без привязки их иначе нет, глобальные слушатели заводятся в `attach()`, и
 *   показанное программно меню осталось бы висеть до `close()`, `Escape`, `Tab` или
 *   клика по пункту.
 *
 *   Поднимаются весь список, а не часть: непривязанный экземпляр, который автоскрытия
 *   прежде не знал, после такой опции спрячется по первому движению курсора.
 *
 *   Правила заводятся на показ и снимаются при закрытии, поэтому экземпляр, который
 *   автор создаёт на каждый показ, ими не течёт. У привязанного экземпляра опция
 *   ничего не меняет: правила уже подняты и держатся между показами, пока жив
 *   `attach()`. `detach()` во время такого показа правила снимает, оставляя меню на
 *   экране: гасить его будет нечем, кроме `close()` и `Escape`.
 *
 *   Нужен меню, которое открывает чужой код — например, действие пункта другого
 *   меню: показ идёт не от нажатия по контейнеру, а из чужого обработчика, и
 *   привязывать ради него контейнер нечем.
 *
 *   По умолчанию `false`, и без опции поведение прежнее.
 */

