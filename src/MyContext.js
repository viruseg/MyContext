/**
 * Расширение типа слушателя для таблицы глобальных обработчиков.
 *
 * `addEventListener` отдаёт обработчику `Event`, а наши обработчики объявлены с
 * узкими типами — `PointerEvent`, `KeyboardEvent` — ради проверок внутри тела.
 * Приводить приходится, и делается это здесь, ровно один раз на обработчик.
 *
 * **Что именно делает приведение.** Параметр-`never` не ограничивает ничего: по
 * контравриантности `never` присваивается любому типу, поэтому такой параметр
 * принимает вообще любую функцию. Параметр типа `Event` был бы ограничиющим, но
 * не годится: под `(event: Event) => void` не подходит ни один обработчик с
 * узким типом, а именно они и нужны. Единственное, что делает приведение
 * допустимым, — сужение до `EventListener` на месте вызова; проверено, что и
 * одиночного приведения достаточно, переход через `unknown` ничего не добавляет.
 *
 * Поэтому безопасность этого места держится **не** на приведении, а на таблице
 * установки: каждая строка вешает обработчик на своё событие, и обработчик
 * `#onGlobalScroll` с типом `Event` читает только `event.target`, тогда как
 * `#onGlobalPointerMove` с типом `PointerEvent` читает `clientX`/`clientY` и
 * получить `Event` не может. Переставить строки местами компилятор не заметит —
 * это цена единственного необходимого приведения, и она описана здесь, а не
 * оставлена без объяснения.
 *
 * @param {(event: never) => void} handler обработчик с узким типом события.
 * @returns {EventListener} тот же обработчик, расширенный до типа слушателя.
 */
function asListener(handler) {
  return /** @type {EventListener} */ (/** @type {unknown} */ (handler));
}

/**
 * Требование платформы проверяется в `attach`, а не в конструкторе: без привязки
 * экземпляр пригоден для `open()` там, где автор и так работает со своим
 * поповером, и падать рано было бы невежливо.
 *
 * @returns {void}
 * @throws {Error} если браузер не умеет показывать поповеры.
 */
function assertPopoverSupport() {
  if (typeof HTMLElement === 'undefined' || typeof HTMLElement.prototype.showPopover !== 'function') {
    throw new Error(POPOVER_REQUIREMENT);
  }
}

/**
 * Глобальный `setTimeout`, званный как метод `globalThis`: отвязанная ссылка на
 * `setTimeout` в некоторых браузерах бросает `Illegal invocation`.
 *
 * @param {() => void} fn
 * @param {number} ms
 * @returns {ReturnType<typeof globalThis.setTimeout>} жест задачи, который
 *   отменяется через `#cancelReopen`.
 */
function defaultSchedule(fn, ms) {
  return globalThis.setTimeout(fn, ms);
}

/**
 * Отмена по жесту от `defaultSchedule`. Глобальный `clearTimeout` зовётся так же
 * как метод `globalThis` — по той же причине, что и `setTimeout` выше.
 *
 * @param {ReturnType<typeof globalThis.setTimeout>} handle
 * @returns {void}
 */
function defaultCancel(handle) {
  globalThis.clearTimeout(handle);
}

/**
 * Оркестратор меню: конфигурация, приватное состояние экземпляра и жизненный цикл.
 * Первый модуль, где встречаются рендерер, слой, движок клавиатуры и hover intent,
 * поэтому половина его работы — не нарисовать, а не разорвать контракты соседей.
 *
 * **Активация: обработчик один, делегированный; владелец подменю по клику открывает
 * подменю, а не зовёт своё действие.** Синтетический `click` движка всплывает, поэтому
 * слушатель один на элемент уровня, ключ берётся у узла (авторский `id` необязателен
 * и повторяем), и второго пути активации у пункта нет. Замысел держит и закрытие:
 * закрывает этот же обработчик, в своём `finally`, — поэтому путь клавиатуры не зовёт
 * закрытия вторым, иначе закрытие было бы двойным, а с ним и возврат фокуса. Клик по
 * владельцу непустого подменю открывает подменю — как в родных меню и как делает
 * `Enter`, который до `host.openSubmenu` доходит напрямую, без синтетического клика,
 * так что пути мыши и клавиатуры не смешиваются. Правило зафиксировано решением
 * ревью Task 9, а не выведено из разметки: `hasSubmenu` у рендерера означает
 * «есть подменю», а не «есть действие».
 *
 * **Показ подменю по мыши — четыре разных события на четырёх разных узлах.**
 * `pointerenter` и `pointerdown` на пункте-владельце, `pointermove` на элементе
 * уровня и `pointerenter` на самом подменю. `pointerenter` и `pointerleave` не
 * всплывают, поэтому пункт подписывается лично — и подписывается ровно тогда,
 * когда рендерер назвал его владельцем, то есть отключённые пункты-владельцы не
 * подписаны ни на что и не открываются ни одной дверью. Решение о том, когда
 * показывать и когда скрывать, принимает `hoverIntent` и сообщает его колбэками
 * `onOpen` и `onClose`; оркестратор не опрашивает `isOpenPending` никогда — опрос
 * был бы вторым источником тиков и сдвинул бы показ относительно решения.
 * `pointermove` передаётся в hover intent не по всему дереву, а мимо
 * пунктов-владельцев: на владельце решать нечего, и там каждое движение курсора
 * планировало бы закрытие подменю, которое только что открылось.
 *
 * **Показанный уровень всегда отдаётся движку через `registerLevel`, а не только
 * корневой.** Движок берёт уровень из своего реестра, а не из DOM, поэтому уровень,
 * которому не звали `registerLevel`, не получает клавиш вовсе, и `close()` сбрасывает
 * реестр — значит повторный `open()` обязан отдать уровень заново. Место у
 * `#openSubmenu` одно, поэтому пути показа — наведение, нажатие, клик и клавиатура —
 * не могут разойтись.
 *
 * **Фокус переносит не показ, а тот, кому он принадлежит.** Корневой уровень берёт
 * фокус на себя: без него меню, открытое программно, не отвечало бы на клавиши.
 * Подменю показывается с `focus: false` — фокус остаётся в родительском уровне
 * (спека 3.2), — и уходят в подменю оба пути по одному правилу: мышиный в подменю
 * фокус не уводит вовсе, курсор остаётся на владельце, и отметка с фокусом стоят на
 * нём, а клавиатурный переносит его движок сам, вызвав `#openSubmenu` и отдав фокус
 * первому доступному пункту нового уровня. Показ подменю переноса не делает не по
 * недосмотру, а потому что показ не владеет фокусом: иначе у мышиного и клавиатурного
 * путей было бы по два места переноса.
 *
 * Показ не отмечает пунктов и в этом не виноват: отметка появляется там, где
 * последним дотронулись до пункта, — мышью или клавишей. Поэтому открытое и
 * нетронутое меню выделения не имеет, а уровень из одних отключённых пунктов и
 * разделителей всё равно зарегистрирован и отвечает на клавиши: разбирать нечего,
 * но и молчать не по чему. Выключают его глобальные обработчики, а не движок.
 *
 * **Уровень подменю заводится на шаг вперёд, но не глубже, и только для доступных
 * владельцев.** Движок ищет подменю по паре «родитель, владелец» и уровни не создаёт,
 * поэтому незаведённый уровень не открылся бы ни по `ArrowRight`, ни по клику — молча.
 * Отключённый владелец в цикл роуминга не входит, кликом не активируется и владельцем
 * не считается: рендерер ставит `hasSubmenu` по непустому подменю **и** доступности,
 * поэтому у него нет ни шеврона, ни `aria-owns`, ни заводимого уровня — обещать
 * раскрытие, которого не будет, не должен ни один слой. Глубже шага заведение не
 * идёт: следующий уровень появится, когда покажется этот, — иначе ленивая постройка
 * веток стала бы постройкой всего дерева при первом открытии.
 *
 * **Цепочка открытых уровней — единственный источник правды о том, что показано.**
 * Слой знает состояние каждого уровня, но не знает, какой из них глубже текущего.
 * Открытие подменю обрезает цепочку до его родителя, то есть уносит всё глубже
 * открытое, — а не закрывает меню целиком: переход на соседний пункт должен оставить
 * открытым уровень, из которого этот пункт и открыт.
 *
 * **«Меню открыто» — это цепочка непуста _или_ показ отложен.** Второе условие
 * обязательно и относится к переоткрытию: в окне между сокрытием и показом цепочка
 * уже пуста, и проверка по одной цепочке сочла бы меню закрытым — третий правый
 * клик подряд прошёл бы мимо цикла и показал меню немедленно, без выхода.
 *
 * **Слушатель `keydown` висит на уровне, а не на документе.** Глобальные слушатели —
 * отдельная задача, и до их появления клавиши адресуются пункту, а не документу.
 * Слушатель уровня пропускает событие, уже погашенное (`event.defaultPrevented`):
 * общий слушатель разберёт клавишу в capture-фазе раньше, и второй разбор не
 * случится, — поэтому переносить его на уровень не придётся.
 */
export class MyContext {
  /** @type {Array<MenuItem | SeparatorItem>} */
  #items;

  /** @type {Required<MyContextOptions>} опции с подставленными дефолтами. */
  #options;

  /** @type {MenuLayer} */
  #layer;

  /** @type {KeyboardController} */
  #keyboard;

  /** @type {HoverIntentController} */
  #hover;

  /**
   * Карта действий всех уровней экземпляра: кладёт рендерер, читает обработчик
   * активации, целиком чистит `destroy()`.
   *
   * @type {Map<string, MenuItem>}
   */
  #actions;

  /**
   * Уровни, заведённые слоем, по элементу уровня. Нужен и для поиска уровня по цели
   * события, и для того, чтобы обработчики уровня навешивались ровно один раз.
   *
   * @type {Map<HTMLElement, LevelEntry>}
   */
  #levels;

  /**
   * Пункты, на которые подписан показ подменю, по узлу пункта. Это ровно те
   * владельцы, которые роуминг может сделать активными: отключённые владельцы сюда
   * не попадают, и наведение, нажатие и движение курсора по ним никуда не идут.
   * Нужен и обработчикам показа, и проверке «курсор на пункте-владельце» в
   * `pointermove` уровня.
   *
   * @type {Map<Element, RenderedItem>}
   */
  #showTargets;

  /**
   * Открытые уровни от корня к текущему. Единственный источник правды о том, что
   * показано: `#layer` знает состояние каждого уровня, но не знает, какой из них
   * глубже текущего, и без этой строки усечение цепочки было бы негде искать.
   * Первый элемент — всегда корень.
   *
   * @type {LevelEntry[]}
   */
  #chain;

  /**
   * Владелец, под подменю которого зреет отложенное открытие. Заполняется
   * наведением, читается колбэком `onOpen`: решение о показе принимает
   * `hoverIntent` по своим таймерам, а предмет показа — оркестратор, и он не
   * выводится из DOM заново.
   *
   * @type {RenderedItem | null}
   */
  #hoverOwner;

  /** @type {LevelEntry | null} */
  #root = null;

  /** @type {HTMLElement | null} */
  #attachedTo = null;

  /** @type {HTMLElement | null} */
  #focusOwner = null;

  /**
   * Счётчик показов: растёт на каждом вызове `open()`.
   *
   * Нужен ровно для одной вещи — отличить «действие пункта открыло меню заново»
   * от «действие пункта отработало в уже показанном меню». Обработчик активации
   * читает значение до вызова действия и в `finally` пропускает закрытие, если
   * значение изменилось: закрытие, начатое по клику, убило бы то, что действие
   * только что открыло, и «открыть меню в другом месте» из обработчика пункта
   * было бы попросту невозможно. Вопрос задаётся счётчиком, а не состоянием
   * меню: состояние — вещь плана, а поколение показов единственное отвечает на
   * вопрос «то ли это показ».
   *
   * Второе назначение — охрана отложенного показа переоткрытия, и она того же
   * рода: показ отложен, и к его моменту поколение могло сменить уже другое
   * `open()`. Показ читает запомнившийся счётчик и молчит при расхождении, то
   * есть «показать не то поколение» ему так же нельзя, как обработчику активации
   * — закрыть не то.
   *
   * @type {number}
   */
  #openSerial = 0;

  /**
   * Последняя известная точка курсора: из неё `onClose` решает, докуда закрывать.
   *
   * Нужна потому, что сигнал закрытия один, а уровней в каскаде много. `hoverIntent`
   * планирует закрытие на движение и срабатывает один раз, поэтому объём закрытия
   * должен решить он сам: закрывать по одному уровню на каждое движение мышью
   * значило бы, что остановившийся курсор оставляет подменю висеть и убрать их
   * больше нечем. За один сигнал закрывается самый глубокий уровень, сколько всего —
   * решает глубина цепочки.
   *
   * Заполняется в `#feedPointerMove`, а зовут его оба обработчика движения — внутри
   * дерева меню и вне его: иначе точка устаревала бы от движения по самому меню. На
   * пункте-владельце не заполняется, и это не потеря: там `pointerMove` не зовётся
   * вовсе, а отложенное закрытие снимает вход на пункт, то есть к моменту срабатывания
   * таймера читать точку уже не нужно.
   *
   * Обнуляется в `#forgetPlacement()`, а `#forgetPlacement()` зовут `open()` на
   * открытом меню, `#closeMenu()` и `destroy()`: точка прежней постановки не должна
   * сносить каскад новой, а после закрытия её читать нечего.
   *
   * @type {Point | null}
   */
  #lastPointerPoint = null;

  /**
   * Жест отложенного показа при переоткрытии; `null`, когда показ не отложен.
   *
   * `null` — признак висящего показа, а не «меню закрыто»: в окне между сокрытием
   * и показом меню ещё не закрыто, но уже и не показано, и любое закрытие обязано
   * снять этот жест, иначе `Escape` воскресил бы меню.
   *
   * Тип — тот, что возвращает таймер: жест задачи принадлежит глобальному
   * `setTimeout`, и `defaultSchedule` ничего своего не добавляет.
   *
   * @type {ReturnType<typeof globalThis.setTimeout> | null}
   */
  #reopenHandle = null;

  /**
   * Запрос `prefers-reduced-motion: reduce` для решения о пропуске отложенности
   * показа. Значение `.matches` читается в момент переоткрытия, поэтому смена
   * настройки движка влияет на уже созданный экземпляр.
   *
   * Медиазапрос свой, а не слойский: пропускать ли отложенность, решает владелец
   * таймера, и тот же вопрос про закрытие у слоя и про показ у оркестратора — один,
   * но решения их разные.
   *
   * @type {MediaQueryList}
   */
  #reducedMotionQuery;

  /**
   * Глобальные слушатели: узел, имя события и сама функция. Снимаются все разом по
   * списку, поэтому `detach()` и `destroy()` не могут оставить ни одного, а
   * добавить обработчик, забыв его снять, structurally невозможно.
   *
   * @type {GlobalHandlerRow[]}
   */
  #globalHandlers = [];

  /** @type {boolean} */
  #destroyed = false;

  /**
   * Единственный обработчик активации: один на элемент уровня, ни одного на
   * пункте. Ссылка на стрелку неизменна, поэтому `removeEventListener` снимает
   * именно тот обработчик, который был навешан.
   *
   * @type {(event: MouseEvent) => void}
   */
  #onLevelClick = (event) => {
    if (this.#destroyed) {
      return;
    }
    // `currentTarget`, а не цель: слушатель навешен на элемент уровня, и уровень
    // известен без обхода дерева — у события, всплывшего с пункта, цель другая.
    const level = event.currentTarget;
    if (!(level instanceof HTMLElement)) {
      return;
    }
    const entry = this.#levels.get(level);
    if (entry === undefined) {
      return;
    }
    const target = event.target;
    if (!(target instanceof Element)) {
      return;
    }
    const element = target.closest(ITEM_SELECTOR);
    if (element === null) {
      return;
    }
    const rendered = this.#focusableIn(entry, element);
    // Ключ есть у пункта и отсутствует у разделителя, а доступность отсекла и его,
    // и отключённый пункт: клик по отключённому не действие, и закрывать им меню
    // нечем.
    if (rendered === null || rendered.key === null) {
      return;
    }
    // Владелец непустого подменю по клику открывает подменю, а своё действие не
    // зовёт — так же, как это делает `Enter`, и так же, как в родных меню. Решение
    // ревью Task 9, а не вывод из разметки: `hasSubmenu` у рендерера означает «есть
    // подменю», и наличие собственного действия этому не противоречит.
    if (rendered.hasSubmenu) {
      // Открытие подменю — тот же путь, что и по наведению: одно тело, один
      // `ensureLevel` и одно место, где показанный уровень отдаётся движку.
      this.#showSubmenuFor(rendered);
      return;
    }
    const item = this.#actions.get(rendered.key);
    if (item === undefined) {
      return;
    }
    // Поколение показов читается до действия: действие вправе открыть меню в
    // другом месте, и тогда закрытие, начатое по этому же клику, убило бы то, что
    // только что открыто.
    const serial = this.#openSerial;
    try {
      // Обработчика может не быть, и это не повод оставить меню висеть: клик по
      // доступному пункту закрывает меню всегда, а наличие `action` — свойство
      // пункта, а не условие закрытия.
      item.action?.(event);
    } finally {
      // Закрытие обязано быть в `finally`, а не после вызова: обработчик, бросивший
      // исключение, иначе оставил бы меню висеть. Само исключение наружу не уходит
      // пойманным — его получает вызывающий, как и любую другую ошибку его
      // обработчика. Пропуск закрытия не имеет права глушить его, поэтому обе
      // проверки сведены в одну положительную: `return` из `finally` заменил бы
      // висящее исключение своим значением. Действие, уничтожившее экземпляр, уже
      // снесло меню, и `close()` после `destroy()` бросил бы ошибку поверх результата
      // действия.
      if (this.#openSerial === serial && !this.#destroyed) {
        this.close();
      }
    }
  };

  /**
   * @type {(event: KeyboardEvent) => void}
   */
  #onLevelKeydown = (event) => {
    if (this.#destroyed || event.defaultPrevented) {
      return;
    }
    this.#keyboard.handleKeydown(event);
  };

  /**
   * Движение курсора по дереву меню. Первым делом оно выделяет пункт под курсором:
   * выделение достаётся последнему, кто тронул меню, и потому мышь перебивает
   * клавиатуру без отдельного правила. Отдельно от этого движение кормит
   * `hoverIntent` — и кормит не по всему дереву, а мимо пунктов-владельцев: на
   * владельце решать нечего, там подменю вот-вот откроется или уже открыто, а
   * безопасная область выводится из геометрии цепочки, а не из траектории, — и
   * планировать по нему закрытие значило бы мигать на месте.
   *
   * @type {(event: PointerEvent) => void}
   */
  #onLevelPointerMove = (event) => {
    if (this.#destroyed) {
      return;
    }
    const target = event.target;
    if (!(target instanceof Element)) {
      return;
    }
    const item = target.closest(ITEM_SELECTOR);
    const level = target.closest(MENU_SELECTOR);
    if (item !== null && level instanceof HTMLElement) {
      const entry = this.#levels.get(level);
      if (entry !== undefined) {
        const rendered = this.#focusableIn(entry, item);
        if (rendered !== null) {
          this.#keyboard.activateFromPointer(entry, rendered);
        }
      }
    }
    if (item !== null && this.#showTargets.has(item)) {
      return;
    }
    this.#feedPointerMove({ x: event.clientX, y: event.clientY });
  };

  /**
   * Средняя кнопка мыши не должна ничего делать с меню: по ней браузер запускает
   * автоскролл и вставку выделенного, а `user-select: none` их не отменяет.
   * Гасится всё дерево, поэтому подписка на уровень, а не на пункт: `#onItemDown`
   * висит только на владельцах подменю и блокировать ему нечего.
   *
   * Отдельного слушателя на `mousedown` не нужно: отмена `pointerdown` отменяет и
   * досинтезированное следом совместимое событие.
   *
   * @type {(event: PointerEvent) => void}
   */
  #onLevelPointerDown = (event) => {
    if (this.#destroyed) {
      return;
    }
    if (event.button === MIDDLE_MOUSE_BUTTON) {
      event.preventDefault();
    }
  };

  /**
   * Вход в показанное подменю: запланированное закрытие снимается. Шаг нужен и там,
   * куда безопасная область не достаёт, — при переходе к подменю, прижатому к краю
   * вьюпорта, зазор до владельца там больше `SUBMENU_OFFSET`, и переход держится
   * только на этом снятии.
   *
   * @type {() => void}
   */
  #onSubmenuEnter = () => {
    if (this.#destroyed) {
      return;
    }
    this.#hover.submenuEnter();
  };

  /**
   * @type {(event: PointerEvent) => void}
   */
  #onItemEnter = (event) => {
    if (this.#destroyed) {
      return;
    }
    // `target`, а не `currentTarget`, вопреки правилу обработчиков уровня: сюда
    // `pointerenter` подписан лично на сам пункт, и всплытия нет вовсе, так что
    // `currentTarget` совпал бы с целью. Расходиться они могут только если этот
    // обработчик поднять на уровень, а тогда `showTargets.get(target)` вернёт
    // `undefined` и наведение молча перестанет работать.
    const target = event.target;
    if (!(target instanceof Element)) {
      return;
    }
    const rendered = this.#showTargets.get(target);
    if (rendered === undefined) {
      return;
    }
    this.#hoverOwner = rendered;
    this.#hover.itemEnter();
  };

  /**
   * @type {() => void}
   */
  #onItemLeave = () => {
    if (this.#destroyed) {
      return;
    }
    this.#hover.itemLeave();
  };

  /**
   * @type {(event: PointerEvent) => void}
   */
  #onItemDown = (event) => {
    if (this.#destroyed) {
      return;
    }
    // Только основная кнопка. Правый клик подтверждается `contextmenu`, который
    // зовёт `open()`, и меню гаснет, а не переезжает: подменю, открытое нажатием,
    // мигнуло бы ровно на один такт — а против чего безопасная область и строится.
    // Средняя кнопка не открывает ничего и по существу.
    if (event.button !== PRIMARY_MOUSE_BUTTON) {
      return;
    }
    // Удержание кнопки открывает подменю немедленно, минуя `openDelayMs`. Само
    // событие не разбирается: `itemPress` молчит, если висящей задачи открытия
    // нет, а «уже открытое подменю» от неё неотличимо — задача снята и уходом с
    // пункта, и `cancelAll`.
    this.#hover.itemPress();
  };

  /**
   * @type {(event: MouseEvent) => void}
   */
  #onContextMenu = (event) => {
    if (this.#destroyed) {
      return;
    }
    event.preventDefault();
    this.open({ x: event.clientX, y: event.clientY });
  };

  /**
   * Движение курсора в пустоте страницы. Внутри дерева движение разбирает
   * `#onLevelPointerMove` — и намеренно не там, где стоит пункт-владелец, потому
   * что по владельцу решать нечего. Этот обработчик берёт то, чего уровни не
   * видят: точку вне меню, включая пустоту страницы и сам привязанный контейнер.
   * Без него подменю переживало бы уход курсора с дерева, потому что планировать
   * закрытие больше было некому.
   *
   * Внутри собственного дерева обработчик молчит, и причина не в порядке событий:
   * пункт-владелец лежит вне безопасной области своего же подменю, поэтому
   * `pointerMove` по нему спланировал бы закрытие, которое сработает сразу после
   * открытия. Замер порядка это подтверждает и в другую сторону: `pointerenter`
   * пункта приходит раньше `pointermove` документа, так что «capture раньше enter»
   * объяснением быть не может. Решение внутри дерева принимает
   * `#onLevelPointerMove`.
   *
   * Над контейнером и над пустотой точка `hoverIntent` получает всегда, и в том
   * числе над контейнером: там событие не достаётся ни одному уровню, и без него
   * планировать закрытие было бы некому — подменю висело бы неограниченно. Объём
   * закрытия от этого не меняется: за один сигнал закрывается самый глубокий
   * уровень, сколько всего — решает глубина цепочки, и колбэк `onClose` работает
   * одинаково в обоих случаях.
   *
   * **Уход с дерева меню сбрасывает выделение целиком.** Здесь оно снимается со всех
   * уровней, а фокус, если он был в меню, встаёт на элемент корневого: по требованию
   * «выделение полностью сбрасывается, как при только что открытом меню» возвращать
   * нечего, а меню обязано снова отвечать на клавиши. Фокус с самой страницы меню не
   * отбирает — решение об этом принимает `clearActive`, и здесь оно лишь не
   * отменяется. Смысл «курсор не в дереве» относится и к привязанному контейнеру:
   * он страница, а не меню.
   *
   * Сброс идёт до `pointerMove` и не зависит от него, поэтому пунктом-владельцем не
   * прикрывается: этот обработчик молчит внутри дерева, и уход на владельца сбрасывать
   * не должен.
   *
   * Цикл закрытия планируется на каждое движение мыши, открытое меню или нет:
   * `cancelAll`, обход построенного дерева и таймер на каждый уровень при пустом
   * меню тратятся впустую, но состояние, в котором это было бы ошибкой, —
   * меню, открытое после последнего движения, — снимается первым же `open()`,
   * который зовёт `cancelAll`. Цикл к тому же ограничен одним на `CLOSE_GRACE_MS`.
   * Проверка «открыто ли меню» перед `pointerMove` дала бы второй источник правды о
   * том, что показано, и со временем разошёлся бы с оркестратором. У `clearActive`
   * проверка своя и по-другому устроена: она спрашивает не оркестратор, а слой, то
   * есть `entry.open` у того уровня, который слой сам же и показывал.
   *
   * @type {(event: PointerEvent) => void}
   */
  #onGlobalPointerMove = (event) => {
    if (this.#destroyed) {
      return;
    }
    if (this.#isInsideMenu(event.target)) {
      return;
    }
    // `open`, а не просто непустая ссылка: закрытое меню держит последний корень
    // прошлой постановки, а закрытый уровень остаётся laid out и потому
    // программно фокусируем — сфокусированным оказался бы элемент невидимого меню.
    // Сегодня платформа уводит фокус из скрытого поповера раньше, так что проверка
    // держит инвариант, а не наблюдаемое различие.
    const root = this.#root;
    if (root !== null && root.open) {
      this.#keyboard.clearActive(root);
    }
    this.#feedPointerMove({ x: event.clientX, y: event.clientY });
  };

  /**
   * Левый клик вне дерева меню, контейнер включая: клик по странице — это уход из
   * меню, и оставлять его висеть после клика по своему же контейнеру значило бы
   * требовать от пользователя правого клика для закрытия.
   *
   * Контейнер исключался из зоны закрытия ради правого клика: тот приходит
   * `pointerdown` раньше `contextmenu`, и меню сперва снесло бы себя, а потом
   * открылось заново, то есть мигнуло бы на каждый правый клик по контейнеру.
   * Исключение снято, потому что правый клик идёт своим путём: `#onGlobalContextMenu`
   * пропускает цель внутри контейнера, а левой кнопки через него не проходит вовсе.
   *
   * @type {(event: PointerEvent) => void}
   */
  #onGlobalPointerDown = (event) => {
    if (this.#destroyed || event.button !== PRIMARY_MOUSE_BUTTON) {
      return;
    }
    if (this.#isInsideMenu(event.target)) {
      return;
    }
    this.#closeMenu({ returnFocus: false });
  };

  /**
   * Правый клик. Внутри меню системное меню подавляется, вне — нет: библиотека не
   * перехватывает правый клик на чужой странице, и системное меню здесь правильный
   * ответ. Порядок браузер отдаёт `pointerdown` раньше `contextmenu`, так что
   * правый клик снаружи закрывает меню уже первым событием, а второе лишь
   * подтверждает, что подавлять нечего.
   *
   * @type {(event: MouseEvent) => void}
   */
  #onGlobalContextMenu = (event) => {
    if (this.#destroyed) {
      return;
    }
    const target = event.target;
    if (this.#isInsideMenu(target)) {
      event.preventDefault();
      return;
    }
    if (this.#isInsideAnchor(target)) {
      return;
    }
    this.#closeMenu({ returnFocus: false });
  };

  /**
   * `Escape` вне дерева. Внутри дерева клавишу разбирает движок на самом уровне,
   * и второй разбор означал бы двойное закрытие: `#closeCurrentLevel` закрывает
   * один уровень, а здесь закрылась бы цепочка — мимо `Escape` внутри меню, где
   * пользователь имеет право закрыть один уровень и остаться в остальных.
   *
   * Проверяется именно дерево, а не дерево вместе с контейнером: фокус на
   * контейнере — обычное состояние после клика по кнопке, и оставлять там
   * клавиатурного пользователя с открытым меню без единого выхода нельзя.
   * Контейнер не часть меню, и `Escape` на нём — уход из меню, а не шаг внутри.
   *
   * Показ переоткрытия отложен: уровень, с которого пришла клавиша, уже гаснет, его
   * реестр в движке пуст (спека 5.4), и разбирать `Escape` больше некому. Пропуск
   * «внутри меню» здесь оставил бы висящий показ, и меню воскресло бы.
   *
   * Этот путь возвращает фокус, а у скролла, `resize` и клика — нет, и разница по
   * существу: в окне закрытия фокус наш, он стоит на гаснущем уровне, и оставить его
   * там нельзя — через анимацию `hidePopover()` роняет его на `<body>`, то есть
   * клавиатурный пользователь, закрывший меню `Escape`, оказался бы в начале
   * документа. В живом меню тот же `Escape` возвращает фокус через `closeAll()`, так
   * что одна клавиша не должна давать два разных ответа по фокусу.
   *
   * @type {(event: KeyboardEvent) => void}
   */
  #onGlobalKeydown = (event) => {
    if (this.#destroyed || event.key !== 'Escape' || event.defaultPrevented) {
      return;
    }
    if (this.#reopenHandle !== null) {
      this.#closeMenu({ returnFocus: true });
      return;
    }
    if (this.#isInsideMenu(event.target)) {
      return;
    }
    this.#closeMenu({ returnFocus: false });
  };

  /**
   * Скролл и `resize` закрывают меню: показано оно было для старой геометрии.
   *
   * `scroll` ловится на `window` в capture-фазе, потому что `scroll` не всплывает
   * и на элементе сбрасывает событие до цели, — а нужно узнать, что оно пришло из
   *нутри меню: прокрутка длинного списка не должна его сносить. Внутренним считается
   * ровно тот скролл, чья цель лежит в дереве меню, и это говорит `#isInsideMenu`.
   * Проверка «цель не `document` и не `body`» была бы верна только на страницах,
   * где между документом и меню не прокручивается ничего, — а типовой каркас
   * приложения с обёрткой `overflow: auto` прокручивает именно её, и меню осталось
   * бы висеть оторванным от якоря.
   *
   * @type {(event: Event) => void}
   */
  #onGlobalScroll = (event) => {
    if (this.#destroyed) {
      return;
    }
    if (this.#isInsideMenu(event.target)) {
      return;
    }
    this.#closeMenu({ returnFocus: false });
  };

  /**
   * @type {() => void}
   */
  #onGlobalResize = () => {
    if (this.#destroyed) {
      return;
    }
    this.#closeMenu({ returnFocus: false });
  };

  /**
   * @param {EventTarget | null} target
   * @returns {boolean} цель внутри элемента любого уровня меню.
   */
  #isInsideMenu(target) {
    if (!(target instanceof Element)) {
      return false;
    }
    const level = target.closest(MENU_SELECTOR);
    return level instanceof HTMLElement && this.#levels.has(level);
  }

  /**
   * @param {EventTarget | null} target
   * @returns {boolean} цель внутри привязанного контейнера.
   */
  #isInsideAnchor(target) {
    const anchor = this.#attachedTo;
    return anchor !== null && target instanceof Node && anchor.contains(target);
  }

  /**
   * Создаёт меню. Слушателей на страницу не вешает: `attach` делает это отдельно,
   * и до него экземпляр пригоден для программного `open()`.
   *
   * Дерево пунктов читается лениво, при первом показе уровня, и хранится по
   * ссылке: копия конфигурации обошлась бы в обход объектов-действий, а автор,
   * сменивший набор пунктов до первого открытия, получит именно его.
   *
   * @param {Array<MenuItem | SeparatorItem>} items пункты меню. Пустой массив и
   *   негодный пункт отклоняются здесь же, до появления экземпляра.
   * @param {MyContextOptions} [options] тема, анимация и доступное имя.
   * @throws {TypeError} если конфигурация негодна; путь до поля — в сообщении.
   */
  constructor(items, options = {}) {
    this.#validate(items);
    this.#validateOptions(options);
    this.#items = items;
    this.#options = {
      theme: options.theme ?? 'auto',
      animationDuration: options.animationDuration ?? DEFAULT_ANIMATION_DURATION,
      label: options.label ?? DEFAULT_MENU_LABEL,
    };
    this.#actions = new Map();
    this.#levels = new Map();
    this.#showTargets = new Map();
    this.#chain = [];
    this.#hoverOwner = null;
    this.#reducedMotionQuery = globalThis.matchMedia('(prefers-reduced-motion: reduce)');
    this.#layer = createLayer({
      label: this.#options.label,
      theme: this.#options.theme,
      animationDuration: this.#options.animationDuration,
      actions: this.#actions,
    });
    // `hoverIntent` решает, когда показывать и когда скрывать, и решает это
    // колбэками, а не опросом `isOpenPending`: опрос превратил бы модуль в
    // источник тиков, и решение о показе принималось бы в другое мгновение, чем
    // его вынес `hoverIntent`. Предмет показа — уже наш, `#hoverOwner` кладёт его
    // наведение, а показывать и скрывать — тела ниже.
    this.#hover = createHoverIntent({
      onOpen: () => {
        const owner = this.#hoverOwner;
        if (owner !== null) {
          this.#showSubmenuFor(owner);
        }
      },
      onClose: () => {
        // Один сигнал закрытия уносит весь каскад подменю, а не один уровень:
        // сигналов столько, сколько движений мышью, а остановившийся курсор движений
        // не шлёт, и после одного ухода из меню подменю оставались бы висеть, и
        // убрать их было бы нечем.
        //
        // Область пересчитывается на каждом шаге: она выводится из самого глубокого
        // уровня, а он после каждого скрытия становится следующим. Цикл встаёт, когда
        // точка оказывается внутри области текущего уровня, — это и есть возврат
        // курсора к показанному подменю: уводить дальше нечего. Корень цикл не
        // трогает, у него нет владельца, и закрывать ему нечего.
        const point = this.#lastPointerPoint;
        let deepest = this.#deepestChainEntry();
        while (point !== null && deepest !== null && deepest.ownerItem !== null) {
          if (this.#pointerInsideSafeArea(point)) {
            break;
          }
          this.#hideSubmenuFor(deepest.ownerItem);
          deepest = this.#deepestChainEntry();
        }
      },
    });
    this.#keyboard = createKeyboard(this.#keyboardHost());
  }

  /**
   * Навешивает слушатель `contextmenu` на контейнер.
   *
   * Повторный вызов переносит привязку: предыдущий контейнер молча освобождается,
   * иначе у экземпляра было бы два контейнера, а меню открывалось бы с двух сторон.
   *
   * @param {HTMLElement} element контейнер.
   * @returns {void}
   * @throws {Error} если экземпляр уничтожен или браузер не умеет Popover API.
   */
  attach(element) {
    this.#assertAlive();
    assertPopoverSupport();
    this.#unbind();
    this.#attachedTo = element;
    element.addEventListener('contextmenu', this.#onContextMenu);
    this.#bindGlobalHandlers();
  }

  /**
   * Снимает слушатель `contextmenu`, ничего не разрушая: экземпляр остаётся
   * пригодным для `open()`. Вызов без привязки — не операция.
   *
   * @returns {void}
   * @throws {Error} если экземпляр уничтожен.
   */
  detach() {
    this.#assertAlive();
    this.#unbind();
  }

  /**
   * Открывает корневой уровень в точке вызова. На закрытом меню показ синхронен, на
   * открытом — проходит полный цикл: уровни гаснут на месте, в Top Layer, и через
   * `animationDuration` корневой показывается в новой точке. Уровень и его пункты при
   * этом не пересоздаются, то есть повторный вызов не заводит второго меню.
   *
   * Под `prefers-reduced-motion: reduce` отложенность пропускается целиком, и цикл
   * проходит за один такт.
   *
   * @param {Point} params точка вызова в координатах вьюпорта, px.
   * @returns {void}
   * @throws {Error} если экземпляр уничтожен.
   */
  open(params) {
    this.#assertAlive();
    // Первым делом и до всего: счётчик должен увидеть новое поколение раньше любого
    // обработчика, который успеет отреагировать на показ.
    this.#openSerial += 1;
    // Владельцем фокуса становится контейнер, а не вызвавший код: без привязки
    // возвращать фокус некуда, и `close()` обязан пережить это молча.
    this.#focusOwner = this.#attachedTo;
    // Ответ задан до снятия отложенного показа, а не после: висящий показ и есть
    // признак того, что меню считается открытым. Проверка после снятия сочла бы
    // меню закрытым, и третий клик подряд показал бы его немедленно — то есть
    // прошёл бы мимо цикла, ради которого цикл и заведён.
    const reopening = this.#isShowing();
    this.#cancelReopen();
    if (!reopening) {
      this.#showAt(params);
      return;
    }
    // Подменю прежней постановки привязаны к прямоугольникам своих
    // пунктов-владельцев, а меню уезжает в новую точку, поэтому скрывается вся
    // цепочка, корневой уровень включительно: иначе меню мигнуло бы, переехав из
    // одной точки в другую.
    this.#hideChain();
    this.#forgetPlacement();
    // Под `reduce` отложенность пропускается целиком, а не сокращается, — по той же
    // причине, что и в слое: `transition: none` погасил бы уровень мгновенно, и
    // состояния «меню гаснет в Top Layer», ради которого отложенность и нужна, не
    // существовало бы вовсе. Медиазапрос читается здесь, а не в конструкторе, —
    // решение принимается в момент переоткрытия.
    if (this.#reducedMotionQuery.matches) {
      this.#showAt(params);
      return;
    }
    // Задача закрытия, которую только что поставил слой внутри `hide()`, встанет в
    // очередь раньше этой: таймеры одного тика детерминированы по порядку постановки,
    // и потому выходная анимация всегда доигрывает до конца, а кадра без меню не
    // бывает. На отложенный показ смотрят обе охраны: `#cancelReopen` снимает его
    // в каждом закрытии, а эти проверки — страховка на пути, где отмены не было.
    const serial = this.#openSerial;
    this.#reopenHandle = defaultSchedule(() => {
      this.#reopenHandle = null;
      if (this.#destroyed || this.#openSerial !== serial) {
        return;
      }
      this.#showAt(params);
    }, this.#options.animationDuration);
  }

  /**
   * Считается ли меню открытым: цепочка непуста либо показ отложен.
   *
   * @returns {boolean}
   */
  #isShowing() {
    return this.#chain.length > 0 || this.#reopenHandle !== null;
  }

  /**
   * Снимает отложенный показ переоткрытия.
   *
   * Зовётся из каждого закрытия — `close()`, глобальных обработчиков и `destroy()`:
   * `Escape` в окне между сокрытием и показом воскресил бы меню, которого
   * пользователь закрывать уже не собирался.
   *
   * @returns {void}
   */
  #cancelReopen() {
    if (this.#reopenHandle === null) {
      return;
    }
    defaultCancel(this.#reopenHandle);
    this.#reopenHandle = null;
  }

  /**
   * Гасит уровни цепочки от глубоких к корню. Цепочку и её пункт-владельца
   * обнуляет `#forgetPlacement()`, который зовут сразу за ним.
   *
   * Корневой уровень уходит здесь же, хотя `showRoot` покажет его снова: гаснуть
   * должен тот уровень, который виден сейчас, а не тот, который появится в новой
   * точке. Повторное гашение на уже гаснущем уровне слой переживает — оно снимает
   * прежнюю задачу сокрытия и ставит свою, то есть лишних таймеров не оставляет.
   *
   * Пустая цепочка означает, что предыдущий вызов уже погасил корень и освободил
   * цепочку, а его показ ещё не сработал. Гасить тогда нечего, и возобновления
   * гашения не будет: задача сокрытия от предыдущего вызова уйдёт раньше задачи
   * показа от этого, и между ними возникнет кадр без меню. Перезапуск гашения
   * возвращает обоим задачам одну длительность, и порядок постановки снова делает
   * своё дело.
   *
   * @returns {void}
   */
  #hideChain() {
    if (this.#chain.length === 0) {
      if (this.#root !== null) {
        this.#layer.hide(this.#root);
      }
      return;
    }
    for (let position = this.#chain.length - 1; position >= CHAIN_ROOT_INDEX; position -= 1) {
      this.#layer.hide(this.#chain[position]);
    }
  }

  /**
   * Забывает текущую постановку меню: hover intent, цепочку, пункт-владельца
   * отложенного открытия, последнюю точку курсора и отметки роуминга. Отложенный
   * показ переоткрытия сюда не входит: его снимает `#cancelReopen` отдельной строкой
   * в `#closeMenu` и `destroy`, и смешивать два вида отложенного нельзя.
   *
   * Одно тело на закрытие, переоткрытие и `destroy`, и именно поэтому оно одно.
   * Разошлись бы они тихо: закрытие забыло бы точку, а `open()` — нет, и устаревшая
   * точка прежней постановки снесла бы каскад, открытый уже на новом месте.
   *
   * @returns {void}
   */
  #forgetPlacement() {
    // Отложенные задачи hover относятся к прежней постановке: безопасная область —
    // это прямоугольник страницы, которого на новом месте нет. `close()` снимает их
    // по той же причине, и `open()` не должен быть мягче: ушедшее закрытие снесло бы
    // подменю, открытое уже на новом месте, а ушедшее открытие сорвало бы отсчёт
    // задержки, начатый до переоткрытия.
    this.#hover.cancelAll();
    this.#chain.length = 0;
    this.#hoverOwner = null;
    // Точка курсора относится к прежней постановке: по ней свежий каскад сносить
    // нельзя, а откуда он будет закрываться — известно только после нового
    // движения мышью.
    this.#lastPointerPoint = null;
    this.#keyboard.reset();
  }

  /**
   * Показывает корневой уровень в точке: заводит уровень, ведёт его в цепочку,
   * заводит шаг вперёд и отдаёт уровень движку клавиатуры.
   *
   * Одно тело на синхронное открытие и на отложенное переоткрытие, иначе «меню,
   * перенесённое в новую точку» отличалось бы от только что открытого — по цепочке,
   * по реестру движка и по фокусу, а различие нашлось бы только в анимации.
   *
   * Здесь, а не в `open()`, снимается и hover intent: показ отложен на анимацию, и за
   * это время движение мыши по странице успело запланировать закрытие. Оно
   * относится к меню, которого ещё нет, и с новой постановкой несовместимо.
   *
   * @param {Point} params точка вызова в координатах вьюпорта, px.
   * @returns {void}
   */
  #showAt(params) {
    this.#hover.cancelAll();
    const root = this.#ensureLevel(this.#items, null, 0, null);
    this.#root = root;
    this.#chain.push(root);
    this.#leadAhead(root);
    this.#layer.showRoot(root, params);
    // На каждый показ, а не на первый: после закрытия реестр движка пуст, и без
    // этого вызова меню было бы открытым и мёртвым для клавиатуры.
    this.#keyboard.registerLevel(root, { focus: true });
  }

  /**
   * Закрывает всю цепочку уровней от глубоких к корню, снимает отметки роуминга и
   * отменяет отложенные открытия — подменю и показ переоткрытия, — после чего
   * возвращает фокус элементу-владельцу.
   *
   * Повторяем: `#focusOwner` при возврате не сбрасывается, а движок на корневом
   * уровне зовёт `focusOwner` сам, сразу после `closeAll()`.
   *
   * @returns {void}
   * @throws {Error} если экземпляр уничтожен.
   */
  close() {
    this.#assertAlive();
    this.#closeMenu({ returnFocus: true });
  }

  /**
   * Закрытие без возврата фокуса — путь внешних событий: клик по странице, скролл,
   * `resize`, уход курсора в пустоту. Фокус здесь не наш: он либо остался там, где
   * пользователь его оставил, либо уйдёт по своему пути в браузере, и наш возврат
   * был бы невежливостью — он перехватывал бы фокус при каждом клике по странице.
   * Публичный `close()` и есть этот же путь с `returnFocus: true`, так что
   * контракт Task 9 не меняется, а появляется ровно один новый внутренний.
   *
   * @param {{ returnFocus: boolean }} options вернуть ли фокус привязанному контейнеру.
   * @returns {void}
   */
  #closeMenu({ returnFocus }) {
    this.#cancelReopen();
    this.#layer.hideAll();
    this.#forgetPlacement();
    if (returnFocus) {
      this.#returnFocus();
    }
  }

  /**
   * Снимает слушатель с контейнера, снимает висящие задачи, удаляет все уровни из
   * DOM, очищает карту действий и приватные ссылки. Идемпотентен, в отличие от
   * остальных методов: повторный вызов при размонтировании — обычное дело, и ошибка
   * в нём была бы ошибкой вызывающего кода.
   *
   * @returns {void}
   */
  destroy() {
    if (this.#destroyed) {
      return;
    }
    this.#destroyed = true;
    this.#unbind();
    this.#cancelReopen();
    this.#forgetPlacement();
    this.#layer.destroy();
    // Карта целиком: она принадлежит экземпляру, а не уровню, и рендерер не знает,
    // когда уровень перестал существовать. Частичная очистка оставила бы записи
    // уровней, снесённых перестроением, и уровней, никогда не показанных.
    this.#actions.clear();
    this.#levels.clear();
    this.#showTargets.clear();
    this.#root = null;
    this.#focusOwner = null;
  }

  /**
   * Хост движка клавиатуры: четыре действия, которые движок умеет просить, и ни
   * одного, чего он не умеет. Замыкания на приватные методы, а не ссылка на сам
   * экземпляр: движок получает ровно четыре функции и не может обойти жизненный цикл.
   *
   * @returns {KeyboardHost}
   */
  #keyboardHost() {
    return {
      // Проверка та же, что и на пути мыши в `#onLevelClick`: действие пункта вправе
      // уничтожить экземпляр — «снять с экрана по выбору» обычная форма, — и
      // `closeAll()` после этого бросил бы со стороны движка. Движок о жизненном
      // цикле не знает и знать не должен, поэтому граница проходит здесь.
      closeAll: () => {
        if (!this.#destroyed) {
          this.close();
        }
      },
      openSubmenu: (entry) => {
        this.#openSubmenu(entry);
      },
      closeCurrentLevel: () => {
        this.#closeCurrentLevel();
      },
      focusOwner: () => {
        this.#returnFocus();
      },
    };
  }

  /**
   * Показывает уровень-подменю и заводит шаг вперёд из него.
   *
   * Здесь, а не в вызывающем коде, решаются три вещи сразу, и все три обязательны
   * для любого пути показа — наведение, нажатие, клик и клавиатура:
   *
   * 1. **Усечение цепочки.** Подменю открывается на месте того, ради чего
   *    нажали, а всё, что открыто глубже, уходит: иначе «Экспорт → PDF» осталось
   *    бы висеть поверх подменю «Скачать». Порядок — от глубоких к корню.
   * 2. **Завод уровня движку.** `registerLevel` — единственная регистрация уровня в
   *    движке. Движок берёт уровни из своего реестра, а не из DOM, поэтому
   *    показанный уровень, которому не звали `registerLevel`, не отвечает на
   *    клавиши вовсе: подменю, открытое мышью, было бы видимо и мёртво. Фокус
   *    показ не переносит — перенос принадлежит движку, и оба пути показа ведут
   *    себя одинаково.
   * 3. **Запись в цепочку.** Идентичность уровня задаёт пара «родитель,
   *    владелец», поэтому повторный показ того же подменю после усечения
   *    переиспользует и уровень, и его `id`.
   *
   * @param {LevelEntry} entry уровень-подменю.
   * @returns {void}
   */
  #openSubmenu(entry) {
    if (this.#destroyed) {
      return;
    }
    const parent = entry.parent;
    if (parent !== null) {
      this.#truncateChain(parent);
    }
    this.#layer.showSubmenu(entry);
    this.#leadAhead(entry);
    this.#chain.push(entry);
    this.#keyboard.registerLevel(entry, { focus: false });
  }

  /**
   * Показывает подменю пункта-владельца: находит уровень, из которого владелец
   * открыт, и передаёт показ `#openSubmenu`.
   *
   * Уровень ищется по узлу владельца, а не берётся из аргумента: единственный
   * вызов этого тела — колбэк `onOpen` плюс обработчик активации, и у первого
   * под рукой нет ничего, кроме самого пункта.
   *
   * @param {RenderedItem} rendered пункт-владелец, каким его назвал рендерер.
   * @returns {void}
   */
  #showSubmenuFor(rendered) {
    if (this.#destroyed) {
      return;
    }
    // Правило владельца повторяется здесь намеренно. Вызывающие фильтруют
    // доступность по своей нужде — подпиской на показ и активацией пункта, — но
    // путь показа, оставленный без собственной проверки, откроет подменю
    // отключённого пункта, как только у него появится хоть один новый вызывающий.
    if (!rendered.hasSubmenu || !rendered.focusable) {
      return;
    }
    const level = rendered.element.closest(MENU_SELECTOR);
    if (level === null) {
      return;
    }
    const parent = this.#levels.get(/** @type {HTMLElement} */ (level));
    if (parent === undefined || rendered.key === null) {
      return;
    }
    const item = this.#actions.get(rendered.key);
    if (item === undefined || item.submenu === undefined) {
      return;
    }
    this.#openSubmenu(this.#ensureSubmenuLevel(item.submenu, parent, rendered));
  }

  /**
   * Скрывает подменю пункта-владельца и всё, что открыто из него глубже.
   *
   * Порядок — от глубоких к самому уровню: потомок уходит раньше предка всегда,
   * иначе закрывающийся уровень оставил бы глубокий висеть поверх пустоты.
   * Сама цепочка укорачивается, и следующее усечение отсчитается уже от неё.
   *
   * @param {RenderedItem} rendered пункт-владелец скрываемого подменю.
   * @returns {void}
   */
  #hideSubmenuFor(rendered) {
    const index = this.#chain.findIndex((entry) => {
      return entry.ownerItem === rendered;
    });
    if (index < CHAIN_ROOT_INDEX) {
      return;
    }
    for (let position = this.#chain.length - 1; position >= index; position -= 1) {
      this.#layer.hide(this.#chain[position]);
    }
    this.#chain.length = index;
  }

  /**
   * Обрезает цепочку до указанного уровня включительно: всё глубже него
   * скрывается и исчезает из цепочки. Сам уровень остаётся открытым, и именно
   * поэтому открытие его подменю не уносит родителя.
   *
   * @param {LevelEntry} levelEntry уровень, глубже которого обрезать.
   * @returns {void}
   */
  #truncateChain(levelEntry) {
    const index = this.#chain.indexOf(levelEntry);
    if (index < CHAIN_ROOT_INDEX) {
      return;
    }
    for (let position = this.#chain.length - 1; position > index; position -= 1) {
      this.#layer.hide(this.#chain[position]);
    }
    this.#chain.length = index + 1;
  }

  /**
   * Самый глубокий открытый уровень цепочки либо `null`, когда цепочка пуста.
   *
   * @returns {LevelEntry | null}
   */
  #deepestChainEntry() {
    if (this.#chain.length === 0) {
      return null;
    }
    return this.#chain[this.#chain.length - 1];
  }

  /**
   * Доступный пункт уровня по узлу либо `null`, если это не он.
   *
   * Фильтр один на все двери, где пункт можно тронуть, — активацию кликом и выделение
   * наведением, — и разводить их нельзя: разъехались бы они на первом же пункте, о
   * котором одно мнение, а другое нет, и отключённый пункт стал бы выделяться мышью и
   * не активироваться кликом. Отключённый пункт к тому же не владелец, поэтому
   * активацию подменю этот фильтр отсекает раньше, чем проверка `hasSubmenu`.
   *
   * Здесь же решено, что курсор над невыбираемой строкой выделение не меняет, а не
   * сбрасывает: сбрасывать там нечего, а мигание вышло бы на разделителе высотой в
   * один пиксель, который курсор пересекает постоянно.
   *
   * @param {LevelEntry} entry уровень, на котором искать.
   * @param {Element} element узел пункта.
   * @returns {RenderedItem | null}
   */
  #focusableIn(entry, element) {
    const rendered = entry.items.find((item) => {
      return item.element === element;
    });
    return rendered !== undefined && rendered.focusable ? rendered : null;
  }

  /**
   * Лежит ли точка в безопасной области показанного подменю; на границе — внутри.
   *
   * Правило повторяет `hoverIntent` (`containsArea` в `hoverIntent.js`), и повторять
   * приходится по двум причинам. Первый сигнал закрытия решён ровно этим правилом,
   * и отличие на втором шаге гнало бы каскад мимо первого: точка, посчитанная
   * границей «внутри», обязана и дальше считаться границей «внутри». Наружу модуль
   * правило не отдаёт, а спросить `hoverIntent` нельзя — `pointerMove` планировал бы
   * второе закрытие, и сигнал перестал бы быть один.
   *
   * @param {Point} point точка в координатах вьюпорта.
   * @returns {boolean} `true`, если область есть и точка в ней; области нет — тоже
   *   `true`, потому что закрывать по геометрии тогда нечего.
   */
  #pointerInsideSafeArea(point) {
    const area = this.#safeArea();
    if (area === null) {
      return true;
    }
    return (
      point.x >= area.left
      && point.x <= area.right
      && point.y >= area.top
      && point.y <= area.bottom
    );
  }

  /**
   * Отдаёт движение курсора `hoverIntent` и запоминает точку для цикла закрытия.
   *
   * Одно тело на оба места вызова — внутри дерева меню и вне его, — потому что точка
   * обязана быть свежей в обоих: записать её в одном месте и забыть в другом значило
   * бы сносить каскад по точке, снятой ещё до последнего движения по меню.
   *
   * @param {Point} point точка в координатах вьюпорта.
   * @returns {void}
   */
  #feedPointerMove(point) {
    this.#lastPointerPoint = point;
    this.#hover.pointerMove(point, this.#safeArea());
  }

  /**
   * Прямоугольник, внутри которого курсор считается идущим к подменю, либо `null`,
   * когда подменю не открыто и любое движение планирует закрытие.
   *
   * Прямоугольник подменю расширен по трём сторонам на `SAFE_AREA_BUFFER`, а в
   * сторону пункта-владельца — ровно на зазор: расширение на буфер накрыло бы
   * край соседнего пункта родительского уровня, и уход на него перестал бы
   * закрывать подменю. Считается здесь, а не в `hoverIntent`, потому что здесь
   * есть и владелец, и разворот по X, а модуль остаётся чистой геометрией.
   *
   * @returns {SafeArea | null}
   */
  #safeArea() {
    const deepest = this.#deepestChainEntry();
    if (deepest === null || deepest.ownerItem === null) {
      return null;
    }
    const rect = deepest.element.getBoundingClientRect();
    const pad = SAFE_AREA_BUFFER;
    const gap = SUBMENU_OFFSET;
    const openedLeft = deepest.ownerItem.element.dataset.chevron === 'left';
    if (openedLeft) {
      return { left: rect.left - pad, top: rect.top - pad, right: rect.right + gap, bottom: rect.bottom + pad };
    }
    return { left: rect.left - gap, top: rect.top - pad, right: rect.right + pad, bottom: rect.bottom + pad };
  }

  /**
   * Закрывает тот уровень, где стоит фокус. Уровень берётся из цели события, а не
   * из переменки «текущий»: подменю может быть открыто, а фокус стоять в родителе.
   *
   * Закрытый уровень уходит и из цепочки: она — источник правды о том, что
   * показано, а `Escape` и `ArrowLeft` закрывают уровень в обход `#hideSubmenuFor`.
   * Оставшаяся запись сорвала бы следующую операцию по цепочке: усечение и уход
   * курсора спрятали бы уже скрытый уровень вместо показанного, то есть унесли бы
   * не то. Уровня вне цепочки скрывать нечем, и укорачивать там нечего.
   *
   * Усечение при этом отбрасывает и всё более глубокое, хотя скрывается только
   * сам уровень. Держатся два свойства: скрываемый уровень всегда глубже
   * закрываемого, и фокус никогда не стоит в уровне выше показанного глубже него.
   * Сегодня оба выполняются на каждом пути показа и закрытия, поэтому зависимость
   * латентна — но именно она делает отбрасывание безопасным, и её нужно знать,
   * прежде чем добавлять новый путь закрытия.
   *
   * @returns {void}
   */
  #closeCurrentLevel() {
    const active = document.activeElement;
    if (active === null) {
      return;
    }
    const level = active.closest(MENU_SELECTOR);
    if (level === null) {
      return;
    }
    const entry = this.#levels.get(/** @type {HTMLElement} */ (level));
    if (entry === undefined) {
      return;
    }
    this.#layer.hide(entry);
    const index = this.#chain.indexOf(entry);
    if (index >= CHAIN_ROOT_INDEX) {
      this.#chain.length = index;
    }
  }

  /**
   * Возвращает фокус элементу, вызвавшему меню. Без привязки или после `destroy()`
   * возвращать некуда, и оба случая молчат: фокус остаётся там, где он уже есть.
   *
   * @returns {void}
   */
  #returnFocus() {
    const owner = this.#focusOwner;
    if (owner === null) {
      return;
    }
    // `preventScroll` по той же причине, что и у движка: меню `position: fixed`, и
    // возврат фокуса с прокруткой дёрнул бы страницу в тот момент, когда
    // пользователь её уже отпустил.
    owner.focus({ preventScroll: true });
  }

  /**
   * Заводит уровень в слое и навешивает на его элемент обработчики уровня. Повторный
   * вызов с той же парой «родитель, владелец» возвращает тот же уровень и не
   * добавляет второй обработчик.
   *
   * @param {Array<MenuItem | SeparatorItem>} items пункты уровня.
   * @param {LevelEntry | null} parent уровень, из которого открывается этот; `null`
   *   у корня.
   * @param {number} levelIndex глубина уровня, начиная с 0; идёт в `aria-level`.
   * @param {RenderedItem | null} ownerItem пункт-владелец; `null` у корня.
   * @returns {LevelEntry}
   */
  #ensureLevel(items, parent, levelIndex, ownerItem) {
    const entry = this.#layer.ensureLevel(items, parent, levelIndex, ownerItem);
    if (this.#levels.has(entry.element)) {
      return entry;
    }
    this.#levels.set(entry.element, entry);
    entry.element.addEventListener('click', this.#onLevelClick);
    entry.element.addEventListener('keydown', this.#onLevelKeydown);
    entry.element.addEventListener('pointermove', this.#onLevelPointerMove);
    entry.element.addEventListener('pointerdown', this.#onLevelPointerDown);
    // Вход в подменю снимает отложенное закрытие: у корня нет владельца, и вход в
    // него не означает, что курсор идёт к подменю.
    if (parent !== null) {
      entry.element.addEventListener('pointerenter', this.#onSubmenuEnter);
    }
    return entry;
  }

  /**
   * Заводит уровни подменю на шаг вперёд — ровно для тех пунктов уровня, которые
   * рендерер назвал владельцами и которые роуминг может сделать активными. На тех
   * же пунктах вешается показ по наведению и по нажатию: подписка на показ и
   * заведение уровня решаются одним проходом по одному условию, иначе они
   * разошлись бы — либо у пункта появился бы шеврон, а подменю не открылось бы
   * никогда, либо наоборот.
   *
   * Пункты берутся из карты действий по внутреннему ключу, а не из массива
   * конфигурации: у уровня есть только `RenderedItem`, и подменя у него нет.
   *
   * @param {LevelEntry} entry показываемый уровень.
   * @returns {void}
   */
  #leadAhead(entry) {
    for (const rendered of entry.items) {
      if (!rendered.hasSubmenu || !rendered.focusable || rendered.key === null) {
        continue;
      }
      const item = this.#actions.get(rendered.key);
      // `hasSubmenu` рендерер ставит только непустому подменю доступного пункта, а
      // `submenu` у пункта обязано быть массивом — валидация прошла в
      // конструкторе. Проверка оставлена потому, что карта действий принадлежит
      // экземпляру, а лишнее условие стоит одного сравнения с `undefined` на
      // каждом владельце.
      if (item === undefined || item.submenu === undefined) {
        continue;
      }
      // `addEventListener` не дублирует слушатель с той же ссылкой на том же
      // узле, а показ уровня зовёт этот проход на каждом показе, — повторных
      // подписок не будет.
      this.#showTargets.set(rendered.element, rendered);
      rendered.element.addEventListener('pointerenter', this.#onItemEnter);
      rendered.element.addEventListener('pointerleave', this.#onItemLeave);
      rendered.element.addEventListener('pointerdown', this.#onItemDown);
      this.#ensureSubmenuLevel(item.submenu, entry, rendered);
    }
  }

  /**
   * Заводит уровень-подменю пункта-владельца.
   *
   * Кортеж «пункты, родитель, глубина, владелец» собирается здесь, а не в двух
   * местах: им задаётся идентичность уровня, и ошибка в глубине в одном из них
   * не была бы видна нигде — уровень завелся бы, `aria-level` в нём оказался бы
   * не тем, и разошлись бы только `aria-level` и цепочка.
   *
   * @param {Array<MenuItem | SeparatorItem>} items пункты подменю; непустота и
   *   доступность владельца проверены вызывающим.
   * @param {LevelEntry} parent уровень, из которого подменю открывается.
   * @param {RenderedItem} ownerItem пункт-владелец подменю.
   * @returns {LevelEntry} уровень подменю; тот же самый при повторном заведении.
   */
  #ensureSubmenuLevel(items, parent, ownerItem) {
    return this.#ensureLevel(items, parent, this.#levelIndexOf(parent) + 1, ownerItem);
  }

  /**
   * Глубина уровня. Слой держит её только в `aria-level` уже отрендеренного уровня и
   * наружу не отдаёт, а `levelIndex` нужен и при заведении подменю — считать его
   * приходится здесь.
   *
   * @param {LevelEntry} entry уровень любой глубины.
   * @returns {number} `0` у корня.
   */
  #levelIndexOf(entry) {
    let levelIndex = 0;
    /** @type {LevelEntry | null} */
    let current = entry.parent;
    while (current !== null) {
      levelIndex += 1;
      current = current.parent;
    }
    return levelIndex;
  }

  /**
   * Снимает слушатель `contextmenu` с текущего контейнера. Зовется из `detach`,
   * повторного `attach` и `destroy` — во всех трёх случаях привязка должна исчезнуть
   * ровно один раз и без следа.
   *
   * @returns {void}
   */
  #unbind() {
    this.#unbindGlobalHandlers();
    const target = this.#attachedTo;
    if (target === null) {
      return;
    }
    target.removeEventListener('contextmenu', this.#onContextMenu);
    this.#attachedTo = null;
  }

  /**
   * Навешивает глобальные слушатели. Capture-фаза у документа и окна выбрана одна:
   * событие разбирается раньше любого обработчика страницы, поэтому меню успевает
   * среагировать до того, как авторский код что-то предотвратит. Для `keydown`
   * это ещё и единственный способ закрыть меню, когда фокус ушёл из дерева.
   *
   * Слушатели заводятся на `attach`, а не в конструкторе: до привязки экземпляр
   * пригоден для программного `open()` и страницу трогать не должен.
   *
   * @returns {void}
   */
  #bindGlobalHandlers() {
    /** @type {GlobalHandlerRow[]} */
    const handlers = [
      { target: document, type: 'pointermove', handler: asListener(this.#onGlobalPointerMove) },
      { target: document, type: 'pointerdown', handler: asListener(this.#onGlobalPointerDown) },
      { target: document, type: 'contextmenu', handler: asListener(this.#onGlobalContextMenu) },
      { target: document, type: 'keydown', handler: asListener(this.#onGlobalKeydown) },
      // `passive: true` обязателен именно здесь: обработчик `scroll` не зовёт
      // `preventDefault`, и браузеру не нужно ждать его, чтобы ответить на
      // прокрутку. Опция на снятии повторяется для симметрии строк таблицы, а не
      // ради совпадения: `removeEventListener` смотрит только на `capture`, и
      // расхождение по `passive` подписку не оставляет.
      { target: window, type: 'scroll', handler: asListener(this.#onGlobalScroll), passive: true },
      { target: window, type: 'resize', handler: asListener(this.#onGlobalResize) },
    ];
    for (const entry of handlers) {
      // `AddEventListenerOptions`, а не `EventListenerOptions`: у второго нет поля
      // `passive`, и подписка без `preventDefault` через него не выражается.
      const options = { capture: true, passive: entry.passive === true };
      entry.target.addEventListener(entry.type, entry.handler, options);
    }
    this.#globalHandlers = handlers;
  }

  /**
   * Снимает глобальные слушатели по тому же списку, по которому их вешали: иначе
   * снятие разошлось бы с установкой поимённо, и `destroy()` оставил бы на
   * документе живые обработчики закрытого экземпляра.
   *
   * @returns {void}
   */
  #unbindGlobalHandlers() {
    for (const entry of this.#globalHandlers) {
      const options = { capture: true, passive: entry.passive === true };
      entry.target.removeEventListener(entry.type, entry.handler, options);
    }
    this.#globalHandlers = [];
  }

  /**
   * @returns {void}
   * @throws {Error} если экземпляр уничтожен.
   */
  #assertAlive() {
    if (this.#destroyed) {
      throw new Error(DESTROYED_MESSAGE);
    }
  }

  /**
   * Проверка `options` по той же причине и по тому же правилу, что и для пунктов:
   * негодная опция иначе выдаёт себя за рабочую. Ошибочная `theme` попадает в
   * `data-vc-theme` дословно, и меню в тёмном приложении тихо рисуется светлым;
   * нечисловая длительность даёт недействительный токен `NaNms`, и переход
   * схлопывается в ноль — анимация пропадает без единой ошибки. Обе поломки
   * необратимы и не видны, поэтому проверяем здесь, а не «когда всплывёт».
   *
   * @param {unknown} options опции как их передал вызывающий.
   * @returns {void}
   * @throws {TypeError} на первом негодном поле; путь до поля — в сообщении.
   */
  #validateOptions(options) {
    const path = 'options';
    if (!isRecord(options)) {
      throw new TypeError(`${path}: опции должны быть объектом`);
    }
    const { theme, animationDuration, label } = options;
    if (theme !== undefined && theme !== 'auto' && theme !== 'light' && theme !== 'dark') {
      throw new TypeError(
        `${path}.theme: неизвестная тема «${String(theme)}», ожидается auto, light или dark`,
      );
    }
    if (animationDuration !== undefined) {
      if (typeof animationDuration !== 'number' || !Number.isFinite(animationDuration)) {
        throw new TypeError(
          `${path}.animationDuration: длительность должна быть конечным числом, мс`,
        );
      }
      if (animationDuration < 0) {
        throw new TypeError(`${path}.animationDuration: длительность не может быть отрицательной`);
      }
    }
    // `label` — имя уровня, и оно обязано быть читаемым: пустое имя не читается
    // скринридером и не проходит аудит, а нечисловое попадёт в `aria-label`
    // строкой. Раньше и то и другое проходило молча.
    if (label !== undefined && !isNonEmptyString(label)) {
      throw new TypeError(`${path}.label: имя меню обязано быть непустой строкой`);
    }
  }

  /**
   * Рекурсивная проверка конфигурации.
   *
   * Первым же оператором конструктора: экземпляр с негодной конфигурацией появляться
   * не должен, и сообщение обязано называть путь до поля — вложенность конфигурации
   * с одного взгляда не читается.
   *
   * @param {unknown} items пункты уровня; у корня это `items`, у подменю —
   *   `items[n].submenu`.
   * @param {string} [path] путь до проверяемого набора.
   * @returns {void}
   * @throws {TypeError} на первом негодном поле.
   */
  #validate(items, path = ITEMS_PATH) {
    if (!Array.isArray(items)) {
      throw new TypeError(`${path}: пункты меню должны быть массивом`);
    }
    // Пустой корень — ошибка: меню без пунктов не рисуется, и автор узнал бы об
    // этом только кликом. Пустое подменю — не ошибка, см. `#validateItem`.
    if (items.length === 0) {
      throw new TypeError(`${path}: меню без пунктов не рисуется`);
    }
    items.forEach((item, index) => {
      this.#validateItem(item, `${path}[${index}]`);
    });
  }

  /**
   * @param {unknown} item проверяемый пункт или разделитель.
   * @param {string} path путь до пункта.
   * @returns {void}
   * @throws {TypeError} на первом негодном поле.
   */
  #validateItem(item, path) {
    if (!isRecord(item)) {
      throw new TypeError(`${path}: пункт должен быть объектом`);
    }
    // Разделитель отличается от пункта единственным полем, поэтому проверка идёт по
    // нему же. Объявленное `type` обязано быть ровно `separator`: иначе опечатка
    // автора тихо стала бы пунктом, и меню показало бы строку там, где разделитель.
    if (item.type !== undefined) {
      if (item.type !== SEPARATOR_TYPE) {
        throw new TypeError(
          `${path}.type: разделитель помечается значением "${SEPARATOR_TYPE}", получено ${String(item.type)}`,
        );
      }
      return;
    }
    if (typeof item.label !== 'string' || item.label.trim() === '') {
      throw new TypeError(`${path}.label: пункт обязан иметь непустую подпись`);
    }
    validateIcon(item.icon, `${path}.icon`);
    if (item.action !== undefined && typeof item.action !== 'function') {
      throw new TypeError(`${path}.action: обработчик пункта должен быть функцией`);
    }
    const submenu = item.submenu;
    if (submenu === undefined) {
      return;
    }
    if (!Array.isArray(submenu)) {
      throw new TypeError(`${path}.submenu: подменю должно быть массивом`);
    }
    // Пустое подменю — не подменю, но и не ошибка конфигурации: владельцем его
    // делает рендерер по непустоте массива, и обходить нечего. Проверка непустоты
    // здесь была бы вторым мнением об одном и том же решении.
    if (submenu.length > 0) {
      this.#validate(submenu, `${path}.submenu`);
    }
  }
}
