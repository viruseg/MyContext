/**
 * Геометрия меню для правил, которые смотрят на рамку целиком, а не на пункты.
 *
 * Модуль не знает ни про DOM, ни про меню, ни про курсор: на вход точки и рамки
 * в координатах вьюпорта, на выход одно число. Всё остальное — частности, и
 * держать их здесь незачем.
 *
 * **Откуда берутся рамки и почему это важно.** Уровень входит с анимацией
 * `transform: scale(0.96)`, и `getBoundingClientRect` отдаёт рамку именно
 * текущую, то есть на четыре процента меньше вычисленной. Для правила
 * «курсор далеко ли от меню» такая поправка безобидна: на четыре процента
 * меняется край, а не то, где пользователь стоит относительно меню, и порог,
 * ради которого правило и написано, заведомо много больше четырёх процентов
 * ширины меню. Гораздо важнее другое: рамка приходит та, которую видит
 * человек, а не та, которую вычислил слой, — то есть отступы, поля каркаса и
 * зоны прокрутки уже учтены, и правилу не нужно знать про них ни одного слова.
 */

/**
 * Точка в координатах вьюпорта, px. Та же форма, что у точки вызова у
 * `open({ x, y })`.
 *
 * @typedef {object} Point
 * @property {number} x
 * @property {number} y
 */

/**
 * Прямоугольник в координатах вьюпорта, px.
 *
 * Именно левая верхняя точка с размерами, а не четыре границы: так форму
 * отдаёт `getBoundingClientRect`, и `right`/`bottom` выводятся из неё, а не
 * приезжают вторым источником правды. Поле `DOMRect` подошло бы, но у него
 * `x`/`y` означают левый верхний угол, а `left`/`top` — то же самое, и такая
 * пара имён в подписи вводит в заблуждение при чтении.
 *
 * @typedef {object} Rect
 * @property {number} left
 * @property {number} top
 * @property {number} width
 * @property {number} height
 */

/**
 * Расстояние от точки до прямоугольника, px.
 *
 * Внутри рамки расстояние нулевое: точка в меню — это ноль от меню, и порог
 * автоскрытия на нём не срабатывает в принципе, а не по округлению.
 *
 * Вне рамки отсчёт идёт от края, а по каждой оси отдельно: точка, смещённая
 * на 40 вправо от рамки и лежащая по вертикали внутри неё, находится в 40 от
 * неё, а не в 40 и в вертикальном отступе разом. Расстояние до угла
 * получается само — евклидовым, из двух отступов по гипотенузе.
 *
 * @param {Point} point точка в координатах вьюпорта.
 * @param {Rect} rect прямоугольник в координатах вьюпорта.
 * @returns {number} расстояние, px; `0` внутри рамки.
 */
function distanceToRect(point, rect) {
  const { x, y } = point;
  // Знак «минус конец» схлопывается в ноль, то есть точка за пределами рамки по
  // этой оси даёт положительный отступ, а точка внутри — нулевой.
  const dx = Math.max(rect.left - x, 0, x - (rect.left + rect.width));
  const dy = Math.max(rect.top - y, 0, y - (rect.top + rect.height));
  return Math.hypot(dx, dy);
}

/**
 * Расстояние от точки до ближайшего прямоугольника набора, px.
 *
 * Набор, а не один прямоугольник, потому что открытое меню — это главное окно
 * плюс цепочка подменю, и уход курсора имеет значение только когда он далёк от
 * всех сразу. Ближайший, а не объединённый: между уровнями есть зазор, и он
 * пуст, поэтому рамка, охватывающая оба уровня, считала бы зазор частью меню,
 * и курсор в нём никогда не признавался бы ушедшим.
 *
 * Пустой набор даёт `Number.POSITIVE_INFINITY`: у закрытого меню нет рамки, а
 * расстояние до бесконечности сравнимо с любым конечным порогом и даёт «далеко».
 * Ноль был бы худшим ответом из возможных — он означал бы «курсор на месте»,
 * и пустая цепочка тихо отключала бы правило ровно тогда, когда меню и нет.
 *
 * @param {Point} point точка в координатах вьюпорта.
 * @param {Rect[]} rects прямоугольники в координатах вьюпорта.
 * @returns {number} расстояние до ближайшего, px.
 */
export function nearestRectDistance(point, rects) {
  let nearest = Number.POSITIVE_INFINITY;
  for (const rect of rects) {
    const distance = distanceToRect(point, rect);
    if (distance < nearest) {
      nearest = distance;
    }
  }
  return nearest;
}
